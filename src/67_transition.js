  /* -------------------------------------------------------------------- */
  /* Task 29 (фаза 3) / Task 44: слой, который разворачивает прямоугольник */
  /* в полноэкранный кадр и держит его до stop().                          */
  /*                                                                       */
  /* Волна 2 (ТВ 2026-09-24): переход «постер ряда → кадр карточки» (open) */
  /* удалён вместе с настройкой lumen_transition. Пользователь: «убери     */
  /* этот эффект, когда картинка расползается и открывается карточка       */
  /* фильма». Остался вход reveal(source, opts) — им экран результата      */
  /* рулетки (src/56_roulette.js) разворачивает прямоугольник барабана в   */
  /* кадр выпавшего фильма, — и stop(): его зовут рулетка и старт любого   */
  /* экрана (src/90_runtime.js), чтобы удержанный слой не пережил свой     */
  /* экран. Подробности удержания — в комментарии самого reveal.           */
  /*                                                                       */
  /* Чего слой НЕ делает:                                                  */
  /*  - не ловит клавиши и мышь: pointer-events:none (src/30_css.js) и ни  */
  /*    одного слушателя ввода. Слушатели у слоя есть только про конец     */
  /*    собственного разгона (transitionend/webkitTransitionEnd, held()    */
  /*    ниже) и уходят вместе с узлом;                                     */
  /*  - не снимается сам: ни концом перехода, ни часами — только stop().   */
  /*                                                                       */
  /* Длительности живут ЗДЕСЬ и ставятся инлайном: CSS-файл (src/30_css.js)*/
  /* даёт слою только раскладку. Иначе одно и то же число пришлось бы      */
  /* держать в двух местах — в правиле transition и в таймере ожидания.    */
  /* -------------------------------------------------------------------- */

  LC.transition = (function () {

    /* Длительность разгона — план Task 29 Step 3. */
    var DURATION = 480;
    /* Task 44: сколько reveal() ждёт конца разгона, если события о нём не
       будет вовсе. Вдвое к длительности самого разгона: событие — основной
       путь (переход идёт на композиторе и заканчивается сам), а таймер
       нужен ровно на случай, когда перехода не случилось, — иначе экран
       рулетки остался бы на барабане навсегда, потому что результат
       показывает именно колбэк. Снимать слой таймеру нечем: удержанный
       слой снимает только stop(). */
    var HOLD_WAIT = 960;
    var EASE = 'cubic-bezier(.2,.8,.2,1)';
    /* Запас к масштабу покрытия. Кривая разгона тормозит у самого конца, и
       без запаса последние проценты ширины добираются в самом конце
       разгона: замер живой проверки (2026-09-17) — 98 % ширины экрана на
       320 мс из 480, то есть по 20 px голого экрана с каждого края в самый
       заметный момент. С запасом слой перекрывает экран целиком уже к трети
       перехода. */
    var OVERSCAN = 1.04;

    /* Единственный живой слой: {node, img, timer, frame, done}. Снять его
       может только stop() (его же зовёт следующий show()). timer — ожидание
       конца разгона у reveal, done — колбэк reveal уже отдан, второй раз его
       не зовут. */
    var state = null;

    /* ------------------------------------------------------------------ */
    /* Чистые функции                                                      */
    /* ------------------------------------------------------------------ */

    /* Масштаб и сдвиг от постера в ряду к ПОЛНОМУ экрану.

       Правка пользователя 2026-09-17 (четвёртый круг), дословно: «если ты
       уже делаешь такую анимацию, то надо растягивать, а так это хуйня
       какая-то». Раньше масштаб брался по ВЫСОТЕ: постер вырастал втрое и
       замирал вертикальным прямоугольником 2:3 посреди уже отрисованной
       карточки — не переход, а всплывшая заслонка.

       Теперь масштаб — как у background-size:cover: больший из двух
       отношений, то есть для обычного постера 2:3 на экране 16:9 — по
       ШИРИНЕ. Слой к концу шире и выше экрана по обеим сторонам, лишняя
       высота постера уходит под overflow:hidden оверлея, и на экране
       остаётся полноэкранный горизонтальный кадр — ровно то, что cover
       сделал бы с этим постером в размер экрана. Картинка при этом не
       искажена: масштаб равномерный.

       Максимум, а не минимум, обязателен и для нестандартных карточек:
       у почти квадратного постера покрытие даёт уже высота, а не ширина.

       null — анимировать нечего (карточка без размеров: ряд ещё не
       отрисован или узел скрыт). */
    function geom(rect, screen) {
      if (!rect || !screen) return null;
      var w = Number(rect.width) || 0;
      var h = Number(rect.height) || 0;
      var sw = Number(screen.width) || 0;
      var sh = Number(screen.height) || 0;
      if (w <= 0 || h <= 0 || sw <= 0 || sh <= 0) return null;
      return {
        scale: Math.max(sw / w, sh / h) * OVERSCAN,
        tx: Math.round(sw / 2 - ((Number(rect.left) || 0) + w / 2)),
        ty: Math.round(sh / 2 - ((Number(rect.top) || 0) + h / 2))
      };
    }

    /* ------------------------------------------------------------------ */
    /* Окружение                                                           */
    /* ------------------------------------------------------------------ */

    function motion() {
      try { return LC.motionMode(); } catch (e) { return 'full'; }
    }

    function screenBox() {
      try {
        return { width: window.innerWidth || 0, height: window.innerHeight || 0 };
      } catch (e) {
        return null;
      }
    }

    function raf(fn) {
      try {
        if (window.requestAnimationFrame) return window.requestAnimationFrame(fn);
      } catch (e) { }
      return 0;
    }

    function unraf(id) {
      try {
        if (id && window.cancelAnimationFrame) window.cancelAnimationFrame(id);
      } catch (e) { }
    }

    /* ------------------------------------------------------------------ */
    /* Слой                                                                */
    /* ------------------------------------------------------------------ */

    /* Снять слой: узел, отложенный кадр и таймер. Идемпотентна. */
    function stop() {
      if (!state) return;
      var s = state;
      state = null;
      unraf(s.frame);
      try { if (s.timer) clearTimeout(s.timer); } catch (e) { }
      try { s.node.remove(); } catch (eR) {
        warn('transition: remove failed', eR);
      }
    }

    /* Картинка слоя: big сильнее poster — рулетка отдаёт кадр w1280 фильма
       и постер барабана на случай, если кадра нет.
       Слой удерживается: opacity в списке перехода нет, и разгон её не
       трогает — слой, который «держится до stop()», обязан остаться
       ВИДИМЫМ; страховочного снятия по часам тоже нет. */
    function show(source) {
      var box = screenBox();
      var g = geom(source.rect, box);
      if (!g) return false;

      /* Предыдущий слой снимается целиком: на экране всегда не больше
         одного. */
      stop();

      var node = $('<div class="lumen-overlay"><div class="lumen-overlay__img"></div></div>');
      var img = node.find('.lumen-overlay__img');
      var move = DURATION + 'ms ' + EASE;
      /* Только композиторное свойство transform. Анимация размеров
         (left/top/width/height) тоже дала бы полноэкранный кадр, но её ведёт
         главный поток, и переход замирал на месте (замер живой проверки
         2026-09-17: с 210 по 490 мс размеры не менялись вовсе). */
      /* Префиксное и непрефиксное имя перечисляются в РАЗНЫХ свойствах, а не
         одним списком: в Chrome -webkit-transform — псевдоним transform, и
         список «-webkit-transform …, transform …» дважды называет одно и то
         же свойство. Живьём (2026-09-17) это давало залипший переход: слой
         делал один шаг (230 -> 467 px) и замирал до самого снятия. */
      img.css({
        left: Math.round(source.rect.left) + 'px',
        top: Math.round(source.rect.top) + 'px',
        width: Math.round(source.rect.width) + 'px',
        height: Math.round(source.rect.height) + 'px',
        'background-image': 'url("' + encodeURI(source.big || source.poster) + '")',
        /* Обрез идёт по высоте, и центр постера — обычно не самое важное в
           нём: композиция плаката тяготеет к верхней половине (лица,
           заголовок). Точка кадрирования поднята выше середины, чтобы в
           полноэкранном состоянии оставалось лицо, а не подбородок. */
        'background-position': '50% 38%',
        '-webkit-transition': '-webkit-transform ' + move,
        transition: 'transform ' + move
      });

      $('body').append(node);
      state = { node: node, img: img, timer: null, frame: 0, done: false };
      var live = state;

      /* Разгон задаётся через ДВА отложенных кадра. Один не годится: колбэк
         первого rAF выполняется ещё ДО отрисовки того кадра, в котором слой
         появился, и браузер схлопнул бы начальные и конечные значения в один
         стилевой пересчёт — перехода не было бы вовсе (замер 2026-09-17:
         через 170 мс слой уже стоял в конечной геометрии). Второй кадр
         наступает после того, как картинка на своём месте действительно
         нарисована, и разгон идёт от него. */
      live.frame = raf(function () {
        if (state !== live) return;
        live.frame = raf(function () {
          if (state !== live) return;
          live.frame = 0;
          var tr = 'translate(' + g.tx + 'px, ' + g.ty + 'px) scale(' + g.scale + ')';
          img.addClass('is-run').css({ '-webkit-transform': tr, transform: tr });
        });
      });

      return true;
    }

    /* Task 44: конец разгона удержанного слоя. Растворения у него нет, так
       что transitionend приходит ровно от transform; имя свойства у
       префиксного события движок пишет по-своему (transform или
       -webkit-transform), поэтому сверяется вхождение, а не равенство.
       Событие может не прийти вовсе — на этот случай в reveal стоит
       страховочный таймер, а сам колбэк защищён от второго вызова. */
    function held(el, call) {
      if (!el || typeof el.addEventListener !== 'function') return;
      function done(e) {
        if (e && e.propertyName && ('' + e.propertyName).indexOf('transform') === -1) return;
        call();
      }
      try {
        el.addEventListener('transitionend', done, false);
        el.addEventListener('webkitTransitionEnd', done, false);
      } catch (err) { }
    }

    /* Task 44: слой по ЯВНОМУ источнику и без автоснятия (до волны 2 тем же
       слоем шёл переход «постер → кадр»). Рулетка (src/56_roulette.js) разворачивает
       им прямоугольник барабана в полноэкранный кадр выпавшего фильма и
       держит его, пока экран не покажет результат.

       source = { rect, poster, big } — прямоугольник в координатах окна и
       картинка (big сильнее poster). opts.then — колбэк конца
       разгона: слой к этому моменту уже накрыл экран целиком, и под ним
       можно менять что угодно. Зовётся он РОВНО ОДИН РАЗ, чем бы ни
       кончилось дело — событием или страховочным таймером.

       Чего reveal НЕ делает:
        - не спрашивает LC.hero: источник ему передали;
        - не гасит слой и не снимает его — ни концом перехода, ни часами.
          Снимает только stop(); его зовут следующий show(), рулетка и старт
          любого экрана (src/90_runtime.js), поэтому открытие карточки с
          удержанного экрана убирает слой само.
       Режим «Движение: выкл» reveal всё же уважает: там вызывающий рисует
       результат сразу, без перехода (false — это сигнал «рисуй сам»). */
    function reveal(source, opts) {
      try {
        if (motion() === 'off') return false;
        if (!source || !source.rect) return false;
        if (!source.big && !source.poster) return false;
        if (!show(source)) return false;
        var live = state;
        if (opts && typeof opts.then === 'function') {
          var call = function () {
            if (state !== live || live.done) return;
            live.done = true;
            opts.then();
          };
          held(live.img[0], call);
          live.timer = setTimeout(call, HOLD_WAIT);
        }
        return true;
      } catch (e) {
        warn('transition: reveal failed', e);
        return false;
      }
    }

    return {
      geom: geom,
      reveal: reveal,
      stop: stop,
      active: function () { return !!state; }
    };
  })();

  if (typeof module !== 'undefined' && module && module.lumen) module.exports = LC.transition;
