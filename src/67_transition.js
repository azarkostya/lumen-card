  /* -------------------------------------------------------------------- */
  /* Task 29 (фаза 3): переход «постер ряда → кадр карточки».              */
  /*                                                                       */
  /* Что происходит. Герой главной (src/48_hero.js) на каждом фокусе       */
  /* запоминает фокусную карточку: её УЗЕЛ, адрес уже отрисованного        */
  /* постера и id (LC.hero.lastFocus); прямоугольник узла снимает уже этот */
  /* модуль в момент открытия (Task 37, rectOf). Нажали OK — Lampa         */
  /* шлёт 'activity':start компонента 'full', и если открывают ровно ту    */
  /* карточку, что была под фокусом, мы кладём поверх экрана слой с тем    */
  /* же постером на том же месте и за DURATION мс РАСТЯГИВАЕМ его до       */
  /* полного экрана, растворяя на последней доле. Картинка натянута по     */
  /* cover, поэтому слой всё время заполнен ею целиком, а лишняя высота    */
  /* постера уходит в обрез: к концу на экране полноэкранный горизонтальный*/
  /* кадр, который и подменяется настоящим backdrop карточки (она в это    */
  /* время строится под слоем). Подробности геометрии — в geom().          */
  /*                                                                       */
  /* Чего переход НЕ делает:                                               */
  /*  - не ждёт данных: слой живёт свои DURATION мс независимо от того,    */
  /*    пришёл кадр карточки раньше или позже. Задержать показ карточки он */
  /*    не может — это отдельный узел в body, никто его не дожидается;     */
  /*  - не ловит клавиши и мышь: pointer-events:none (src/30_css.js) и ни  */
  /*    одного слушателя ввода. Два слушателя у слоя всё же есть, но оба   */
  /*    про конец собственного растворения (transitionend/                 */
  /*    webkitTransitionEnd, listen() ниже) и уходят вместе с узлом;       */
  /*  - не остаётся на экране: слой снимает конец собственного растворения,*/
  /*    а если события не будет (переход прерван, вкладка ушла в фон) —    */
  /*    страховочный таймер LIFE, который ставится сразу при показе;       */
  /*  - не показывается в lite/off и на слабом устройстве: режим там не    */
  /*    'full' (на слабом его ставит автодетект, src/68_perf.js).          */
  /*                                                                       */
  /* Почему путей снятия два: переход начинается не тогда, когда мы его    */
  /* задали, а с первым отрисованным кадром, и Lampa в этот момент держит  */
  /* главный поток до 600 мс (замер живой проверки). Часами это не         */
  /* предсказать — снимать обязан сам конец анимации; таймер остаётся      */
  /* страховкой на случай, когда события не будет вовсе.                   */
  /*                                                                       */
  /* Длительности живут ЗДЕСЬ и ставятся инлайном: CSS-файл (src/30_css.js)*/
  /* даёт слою только раскладку. Иначе одно и то же число пришлось бы      */
  /* держать в двух местах — в правиле transition и в таймере снятия.      */
  /* -------------------------------------------------------------------- */

  LC.transition = (function () {

    /* Длительность разгона постера — план Task 29 Step 3. */
    var DURATION = 480;
    /* Доля перехода, на которой постер растворяется (последние 40 %). */
    var FADE_SHARE = 0.4;
    /* Страховочный предел жизни слоя. Он НЕ равен длительности перехода:
       найдено живой проверкой (2026-09-17), что переход начинается не в тот
       момент, когда мы его задали, а с первым отрисованным кадром — а между
       нашим вызовом и этим кадром Lampa строит полную карточку и держит
       главный поток до 600 мс (на первом открытии фильма, когда данные ещё
       не в кэше). Со снятием по таймеру в 700 мс разгон при этом обрывался
       на середине или не успевал начаться вовсе. Теперь слой снимает конец
       самой анимации (transitionend), а таймер остаётся страховкой на
       случай, когда события не будет: переход прерван, вкладка ушла в фон,
       движок события не шлёт. */
    var LIFE = 2500;
    var EASE = 'cubic-bezier(.2,.8,.2,1)';
    /* Запас к масштабу покрытия. Кривая разгона тормозит у самого конца, и
       без запаса последние проценты ширины добираются дольше, чем идёт
       растворение: замер живой проверки (2026-09-17) — 98 % ширины экрана на
       320 мс из 480, то есть по 20 px голой карточки с каждого края в самый
       заметный момент. С запасом слой перекрывает экран целиком уже к трети
       перехода. */
    var OVERSCAN = 1.04;

    /* Единственный живой слой: {node, img, timer, frame}. */
    var state = null;

    /* ------------------------------------------------------------------ */
    /* Чистые функции                                                      */
    /* ------------------------------------------------------------------ */

    /* Масштаб и сдвиг от постера в ряду к ПОЛНОМУ экрану.

       Правка пользователя 2026-09-17 (четвёртый круг), дословно: «если ты
       уже делаешь такую анимацию, то надо растягивать, а так это хуйня
       какая-то». Раньше масштаб брался по ВЫСОТЕ: постер вырастал втрое и
       замирал вертикальным прямоугольником 2:3 посреди уже отрисованной
       карточки — не переход, а всплывшая заслонка.

       Теперь масштаб — как у background-size:cover: больший из двух
       отношений, то есть для обычного постера 2:3 на экране 16:9 — по
       ШИРИНЕ. Слой к концу шире и выше экрана по обеим сторонам, лишняя
       высота постера уходит под overflow:hidden оверлея, и на экране
       остаётся полноэкранный горизонтальный кадр — ровно то, что cover
       сделал бы с этим постером в размер экрана. Картинка при этом не
       искажена: масштаб равномерный.

       Максимум, а не минимум, обязателен и для нестандартных карточек:
       у почти квадратного постера покрытие даёт уже высота, а не ширина.

       null — анимировать нечего (карточка без размеров: ряд ещё не
       отрисован или узел скрыт). */
    function geom(rect, screen) {
      if (!rect || !screen) return null;
      var w = Number(rect.width) || 0;
      var h = Number(rect.height) || 0;
      var sw = Number(screen.width) || 0;
      var sh = Number(screen.height) || 0;
      if (w <= 0 || h <= 0 || sw <= 0 || sh <= 0) return null;
      return {
        scale: Math.max(sw / w, sh / h) * OVERSCAN,
        tx: Math.round(sw / 2 - ((Number(rect.left) || 0) + w / 2)),
        ty: Math.round(sh / 2 - ((Number(rect.top) || 0) + h / 2))
      };
    }

    /* Раскладка прозрачности по времени: гаснем не весь переход, а его
       последнюю долю — пока постер разгоняется, он непрозрачен, и подмена
       на кадр карточки происходит уже «на полном экране». */
    function fade(duration, share) {
      var ms = Math.round(duration * share);
      return { ms: ms, delay: duration - ms };
    }

    /* ------------------------------------------------------------------ */
    /* Окружение                                                           */
    /* ------------------------------------------------------------------ */

    function motion() {
      try { return LC.motionMode(); } catch (e) { return 'full'; }
    }

    function enabled() {
      try { return LC.pref('lumen_transition', true) !== false; } catch (e) { return false; }
    }

    function screenBox() {
      try {
        return { width: window.innerWidth || 0, height: window.innerHeight || 0 };
      } catch (e) {
        return null;
      }
    }

    function raf(fn) {
      try {
        if (window.requestAnimationFrame) return window.requestAnimationFrame(fn);
      } catch (e) { }
      return 0;
    }

    function unraf(id) {
      try {
        if (id && window.cancelAnimationFrame) window.cancelAnimationFrame(id);
      } catch (e) { }
    }

    /* Идентификатор открываемой карточки. У объекта активности Lampa он
       лежит в id, а при открытии из ряда — ещё и в card (объект карточки);
       берём первое, что есть. */
    function idOf(object) {
      if (!object) return null;
      if (object.id != null) return object.id;
      if (object.card && object.card.id != null) return object.card.id;
      return null;
    }

    function sameId(a, b) {
      if (a == null || b == null) return false;
      return String(a) === String(b);
    }

    /* ------------------------------------------------------------------ */
    /* Слой                                                                */
    /* ------------------------------------------------------------------ */

    /* Слой снимается, как только доиграло растворение. События может не
       быть вовсе (старый движок, прерванный переход) — тогда сработает
       страховочный таймер, поэтому отсутствие addEventListener здесь не
       ошибка, а просто более поздняя уборка. */
    function listen(el, live) {
      if (!el || typeof el.addEventListener !== 'function') return;
      function done(e) {
        if (state !== live) return;
        if (e && e.propertyName && e.propertyName !== 'opacity') return;
        stop();
      }
      try {
        el.addEventListener('transitionend', done, false);
        el.addEventListener('webkitTransitionEnd', done, false);
      } catch (err) { }
    }

    /* Снять слой: узел, отложенный кадр и таймер. Идемпотентна. */
    function stop() {
      if (!state) return;
      var s = state;
      state = null;
      unraf(s.frame);
      try { if (s.timer) clearTimeout(s.timer); } catch (e) { }
      try { s.node.remove(); } catch (eR) {
        warn('transition: remove failed', eR);
      }
    }

    /* Task 27 (довесок): картинка слоя. Ряды рисуют постеры в w300, а слой
       растягивает их почти на весь экран — в полноэкранном состоянии такой
       постер мыльный. Герой предзагружает ту же обложку в w500 на покое
       фокуса и кладёт адрес в last.big (src/48_hero.js, scheduleBigPoster):
       успела прийти — берём её, нет — идём на прежнем w300. Ждать здесь
       нечего: обе картинки уже в кэше браузера, и переход не откладывается
       ни на кадр. */
    function show(source) {
      var box = screenBox();
      var g = geom(source.rect, box);
      if (!g) return false;

      /* Предыдущий переход (быстрое открытие-закрытие-открытие) снимается
         целиком: на экране всегда не больше одного слоя. */
      stop();

      var node = $('<div class="lumen-overlay"><div class="lumen-overlay__img"></div></div>');
      var img = node.find('.lumen-overlay__img');
      var f = fade(DURATION, FADE_SHARE);
      var move = DURATION + 'ms ' + EASE;
      /* Растворение — ease-in, а не linear: постер и кадр карточки это
         РАЗНЫЕ картинки, и равномерное гашение выдаёт подмену ровно в
         середине, когда обе видны наполовину. С ease-in первую половину
         своего окна постер почти непрозрачен, а уходит в ноль круто — глаз
         читает это как один кадр, а не как наложение двух. */
      var dim = 'opacity ' + f.ms + 'ms ease-in ' + f.delay + 'ms';
      /* Только композиторные свойства: transform и opacity. Анимация
         размеров (left/top/width/height) тоже дала бы полноэкранный кадр, но
         её ведёт главный поток — а он в этот момент занят построением
         карточки, и переход замирал на месте (замер живой проверки: с 210 по
         490 мс размеры не менялись вовсе). */
      /* Префиксное и непрефиксное имя перечисляются в РАЗНЫХ свойствах, а не
         одним списком: в Chrome -webkit-transform — псевдоним transform, и
         список «-webkit-transform …, transform …» дважды называет одно и то
         же свойство. Живьём (2026-09-17) это давало залипший переход: слой
         делал один шаг (230 -> 467 px) и замирал до самого снятия. */
      var webkitTrack = '-webkit-transform ' + move + ', ' + dim;
      var track = 'transform ' + move + ', ' + dim;

      img.css({
        left: Math.round(source.rect.left) + 'px',
        top: Math.round(source.rect.top) + 'px',
        width: Math.round(source.rect.width) + 'px',
        height: Math.round(source.rect.height) + 'px',
        'background-image': 'url("' + encodeURI(source.big || source.poster) + '")',
        /* Обрез идёт по высоте, и центр постера — обычно не самое важное в
           нём: композиция плаката тяготеет к верхней половине (лица,
           заголовок). Точка кадрирования поднята выше середины, чтобы в
           полноэкранном состоянии оставалось лицо, а не подбородок. */
        'background-position': '50% 38%',
        '-webkit-transition': webkitTrack,
        transition: track
      });

      $('body').append(node);
      state = { node: node, img: img, timer: null, frame: 0 };
      var live = state;

      /* Разгон задаётся через ДВА отложенных кадра. Один не годится: колбэк
         первого rAF выполняется ещё ДО отрисовки того кадра, в котором слой
         появился, и браузер схлопнул бы начальные и конечные значения в один
         стилевой пересчёт — перехода не было бы вовсе (замер 2026-09-17:
         через 170 мс слой уже стоял в конечной геометрии с opacity 0).
         Второй кадр наступает после того, как постер на своём месте
         действительно нарисован, и разгон идёт от него.
         Пока главный поток строит карточку, кадров нет — постер просто
         остаётся лежать на месте своей карточки, а разгон начинается, когда
         поток освободится. Снятие ждёт конца анимации, а не часов, поэтому
         переход в этом случае не обрезается. */
      live.frame = raf(function () {
        if (state !== live) return;
        live.frame = raf(function () {
          if (state !== live) return;
          live.frame = 0;
          var tr = 'translate(' + g.tx + 'px, ' + g.ty + 'px) scale(' + g.scale + ')';
          img.addClass('is-run').css({
            '-webkit-transform': tr,
            transform: tr,
            opacity: 0
          });
        });
      });

      /* Конец растворения — сигнал снимать слой. Слушаем именно opacity:
         transform и opacity кончаются одновременно, но постер к этому
         моменту уже невидим, и лишний кадр с ним на экране никому не
         виден. Слушатель уходит вместе с узлом. */
      listen(img[0], live);

      live.timer = setTimeout(function () {
        if (state !== live) return;
        live.timer = null;
        stop();
      }, LIFE);

      return true;
    }

    /* Task 37: прямоугольник карточки снимается ЗДЕСЬ, в момент открытия, а
       не на каждом переводе фокуса. getBoundingClientRect заставляет браузер
       посчитать раскладку немедленно, и на горячем пути листания рядов это
       было принудительное вычисление на каждое нажатие стрелки; на открытие
       карточки оно одно и происходит в кадре, где ряды всё равно уступают
       место полной карточке.

       Узла может уже не быть в документе: ряд мог перестроиться, пока фокус
       стоял на карточке. Оторванный узел даёт нулевые ширину и высоту, а
       geom() на таком прямоугольнике возвращает null — переход просто не
       показывается, как и для карточки без размеров. */
    function rectOf(node) {
      try {
        if (!node || typeof node.getBoundingClientRect !== 'function') return null;
        var r = node.getBoundingClientRect();
        if (!r) return null;
        return { left: r.left, top: r.top, width: r.width, height: r.height };
      } catch (e) {
        return null;
      }
    }

    /* Точка вызова — 'activity':start компонента 'full' (src/90_runtime.js).
       object — объект активности. true, если переход показан. */
    function open(object) {
      try {
        if (motion() !== 'full') return false;
        if (!enabled()) return false;
        var last = null;
        if (LC.hero && typeof LC.hero.lastFocus === 'function') last = LC.hero.lastFocus();
        if (!last || !last.poster) return false;
        if (!sameId(idOf(object), last.id)) return false;
        var rect = rectOf(last.node);
        if (!rect) return false;
        return show({ id: last.id, poster: last.poster, big: last.big, rect: rect });
      } catch (e) {
        warn('transition: open failed', e);
        return false;
      }
    }

    return {
      geom: geom,
      fade: fade,
      open: open,
      stop: stop,
      active: function () { return !!state; }
    };
  })();

  if (typeof module !== 'undefined' && module && module.lumen) module.exports = LC.transition;
