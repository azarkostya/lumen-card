    /* Ревью волны 1b, п.1: старт ролика отменён тем, что открыто поверх
       (trailerBlocked), или стартом плеера Lampa. Закрываясь, Lampa
       возвращает фокус на ту же карточку тем же событием на том же узле
       (Controller.toggle -> collectionFocus), и гард «фокус не сменился» в
       onFocus его съедал — отсчёт на этой карточке не заводился больше
       никогда. Забываем узел и карточку ролика: возврат фокуса проходит
       onFocus целиком и заводит отсчёт заново. */
    function forgetTrailerFocus() {
      if (!state) return;
      state.focusEl = null;
      state.trailerCard = null;
    }

    /* Ревью раунда хвостов, п.6: отсчёт 8 с идёт, а поверх главной
       открылось то, под чем ролик никто не увидит (меню по долгому OK,
       настройки, поиск, «Расширения», плеер), — Lampa сообщает это сменой
       контроллера (Controller.listener 'toggle'; подписка на весь плагин
       одна — followToggle в src/90_runtime.js, оттуда и вызов). Закрыли
       раньше 8-й секунды — прежде отсчёт шёл дальше, и ролик стартовал
       сразу после закрытия, а не через «восемь секунд покоя». Теперь фокус
       забывается, и его возврат на ту же карточку заводит полные 8 с
       заново — как когда оверлей застал саму 8-ю секунду (scheduleTrailer).
       Класс оверлея Lampa ставит ДО своего Controller.toggle (Select.show,
       Search.open, toggle настроек), поэтому trailerBlocked к проверке уже
       отвечает «да». Смена контроллера без оверлея (шапка, левое меню —
       главную там видно) отсчёт не трогает.
       Ревью правок раунда хвостов, п.1: проверка — через такт, а не в самом
       'toggle'. Снимает класс Lampa не всегда раньше: «Назад» из меню —
       да (close -> hide, потом onBack -> Controller.toggle), а выбор
       пункта — наоборот: onBeforeClose меню карточки зовёт
       Controller.toggle(enabled) (app.min.js:22120-22123; наше меню — open
       в src/63_cardmenu.js), toggle возвращает фокус на карточку и шлёт
       'toggle' (:46297-46314), и только потом goclose -> hide снимает
       selectbox--open (:7027-7033). Синхронная проверка видела ещё
       открытое меню и забывала фокус второй раз — уже после возврата: ролик
       через 8 с стартовал в «забытом» состоянии, и первое же событие фокуса
       той же карточки (пульт или мышь) проходило гард «фокус не сменился»
       и обрывало его. К следующему такту hide отработал.
       Ревью правок раунда хвостов, п.4: уже играющий ролик (отсчёта у него
       нет) снимается, если главная спрятана целиком (homeHidden — поиск,
       «Расширения», SearchInput: .wrap скрыт, а iframe YouTube жил и
       декодировал ролик впустую). Фокус забывается, как у playerHook:
       возврат на ту же карточку после закрытия заводит обычные 8 с. Под
       меню, настройками и шапкой главную видно — ролик играет дальше. */
    function onToggle() {
      if (!state || !(state.trailerTimer || state.trailer)) return;
      setTimeout(function () {
        if (!state) return;
        if (state.trailer && homeHidden()) {
          cancelTrailer();
          forgetTrailerFocus();
          return;
        }
        if (state.trailerTimer && trailerBlocked()) forgetTrailerFocus();
      }, 0);
    }

    /* Старт плеера Lampa ('start', app.min.js:31046/31069) снимает ролик
       героя: без этого долгое OK → «Трейлер» на главной оставляло YouTube
       героя играть под полноэкранным плеером. Подписка живёт, пока смонтирован
       герой (mount/unmount); парковка её не трогает — cancelTrailer на
       запаркованном герое ничего не запускает. */
    var playerHook = null;

    function listenPlayer() {
      if (playerHook) return;
      try {
        if (!window.Lampa || !Lampa.Player || !Lampa.Player.listener || typeof Lampa.Player.listener.follow !== 'function') return;
        playerHook = function () {
          cancelTrailer();
          forgetTrailerFocus();
        };
        Lampa.Player.listener.follow('start', playerHook);
      } catch (e) {
        playerHook = null;
        warn('hero: player listener failed', e);
      }
    }

    function unlistenPlayer() {
      var fn = playerHook;
      playerHook = null;
      if (!fn) return;
      try {
        if (window.Lampa && Lampa.Player && Lampa.Player.listener && typeof Lampa.Player.listener.remove === 'function') {
          Lampa.Player.listener.remove('start', fn);
        }
      } catch (e) {
        warn('hero: player unlisten failed', e);
      }
    }

    /* ------------------------------------------------------------------ */
    /* Task 21 (фаза 3): тематическая атмосфера кадра главной.             */
    /*                                                                     */
    /* Тема берётся по ключевым словам ДЕТАЛЕЙ фильма (они приезжают тем   */
    /* же запросом, что логотипы), поэтому частицы появляются не раньше,   */
    /* чем фокус постоял на карточке и детали пришли: при быстром листании */
    /* ряда не монтируется ни одного канваса.                              */
    /*                                                                     */
    /* Акцент интерфейса тема здесь НЕ трогает (в отличие от карточки):    */
    /* на главной фокус переходит с фильма на фильм каждые несколько       */
    /* секунд, и перекрашивать весь экран под каждый — мельтешение. Цвет   */
    /* кадра главной остаётся за акцентом от постера (Task 24).            */
    /* ------------------------------------------------------------------ */

    /* Волна производительности: сколько частицы стоят после нажатия
       (предикат paused в applyFx ниже). */
    var FX_CALM_MS = 1500;
    /* Зона текста героя для слоя частиц (src/52_fx.js, safeZone). */
    var FX_SAFE = { left: 0, top: 0.4, right: 0.5, bottom: 1, floor: 0.15, feather: 0.08 };

    /* Волна производительности: самотест (src/69_bench.js). benchPreset —
       слой частиц этим пресетом независимо от темы фильма (стадия «+fx»
       меряет частицы на любом фильме); benchHeld — смена кадров стоит,
       кадры меняет сам тест (benchFlip), и тик слайдшоу посреди замера
       покоя испортил бы строку таблицы. Оба снимаются уборкой теста. */
    var benchPreset = null;
    var benchHeld = false;

    function fxHost() {
      if (!state || !state.node) return null;
      var node = state.node.find('.lumen-fx');
      return node && node.length ? node : null;
    }

    /* Снимает частицы и класс темы. Идемпотентна: на снятом герое и на
       слое без канваса не делает ничего. */
    function clearFx() {
      var host = fxHost();
      if (host) {
        try { if (LC.fx) LC.fx.unmount(host); } catch (e) { warn('hero: fx unmount failed', e); }
      }
      /* LC.themes может не быть только в тестах, где 48_hero.js грузится в
         одиночку: в бандле 53 идёт раньше 48 и модуль есть всегда. */
      if (state && state.node && LC.themes) {
        try { state.node.removeClass(LC.themes.classNames()); } catch (e2) { warn('hero: fx class failed', e2); }
      }
    }

    /* Ставит атмосферу по деталям фильма под фокусом. Зовётся после
       загрузки деталей и при смене настройки «Атмосферы» на лету. */
    function applyFx() {
      if (!state) return;
      clearFx();
      if (!LC.fx) return;
      var theme = null;
      if (benchPreset) {
        /* Самотест: пресет принудительно, без класса темы и её цвета. */
        theme = { id: '', preset: benchPreset };
      } else {
        if (!state.details || !LC.themes) return;
        try { theme = LC.themes.forMovie(state.details); } catch (e) { warn('hero: fx theme failed', e); }
      }
      if (!theme) return;
      if (theme.id) {
        try { state.node.addClass('lumen-theme--' + theme.id); } catch (e2) { }
      }
      var host = fxHost();
      if (!host) return;
      try {
        LC.fx.mount(host, theme.preset, {
          color: theme.id && LC.themes ? LC.themes.particleColor(theme) : '#FFFFFF',
          /* Волна «праздники крупнее»: зона текста героя — логотип, мета и
             две строки описания лежат в левой половине нижних трёх пятых
             слоя (замер на стенде 960×540@2 и 2560×1440@1: логотип от 0.45
             высоты слоя, описание до 0.82, правый край текста — до 0.46
             ширины). Частицы там гаснут до 15 %, сцена живёт справа и над
             текстом. */
          safe: FX_SAFE,
          /* Под играющим автотрейлером частицы стоят: ролик занимает весь
             кадр героя, и рисовать поверх него — двойная работа впустую.
             Ревью Task 64: то же в сжатом состоянии. Слой атмосферы при
             уходе фокуса в ряды гаснет (.lumen-hero--compact .lumen-fx,
             src/30_css.js), и рисовать в невидимый канвас незачем.
             Task 70: сам кадр в сжатом состоянии больше не гаснет (решение
             пользователя), но частицы гаснут и паузу держат по-прежнему —
             их цена на этом шаге измерена.
             Ревью 2026-09-22 (п.5): «самым занятым моментом на слабом ТВ»
             этот шаг звать было нельзя. На слабом ТВ слоя частиц нет
             вовсе: LC.fx.mount отдаёт null, когда LC.motionMode() не
             'full' (allowedNow, src/52_fx.js), а тумблер тяжёлых эффектов
             на android/tizen/webos по умолчанию выключен
             (fxHeavyDefault, src/81_prefs.js). Экономия реальна, но она
             целиком про полный режим с включёнными тяжёлыми эффектами —
             там замер Task 64 и делался.
             Предикат зовётся каждый кадр, и когда все слои на паузе, цикл
             уходит с rAF на таймер раз в 500 мс (src/52_fx.js,
             schedule/IDLE_MS).
             Волна производительности (2026-09-24): и FX_CALM_MS после
             каждого нажатия. Нажатие пульта — самый дорогой миг главной
             (смена текста, кадра, подсветки карточки), и перерисовка
             полноэкранного канваса поверх него отнимала кадры ровно там,
             где их видно. Каждое следующее нажатие отсчёт продлевает. */
          paused: function () {
            return !!(state && (state.trailer || state.compact || state.parked ||
              Date.now() - state.focusAt < FX_CALM_MS));
          }
        });
      } catch (e3) {
        warn('hero: fx mount failed', e3);
      }
    }

    /* Снимает всё, что связано с роликом: отложенный старт, ответ
       незавершённого запроса роликов и сам плеер. Идемпотентна — плеер
       уничтожается через свой destroy(), а тот всегда проходит через
       единственный onEnd. Сам запрос роликов не отменяется — нечем
       (loadTrailer); его ответ отсекает поднятый здесь tgen. */
    function cancelTrailer() {
      if (!state) return;
      tgen++;
      stopTimer('trailerTimer');
      stopTimer('videosTimer');
      planDone('stop');
      state.trailerCard = null;
      if (state.trailer) {
        var control = state.trailer;
        state.trailer = null;
        try { if (control.destroy) control.destroy(); } catch (e2) {
          warn('hero: trailer destroy failed', e2);
        }
      }
      markTrailer(false);
      /* onEnd плеера сюда уже не дойдёт — tgen поднят выше, — поэтому
         паузу смены кадров, которую ставил ролик, снимаем сами. */
      trailerOff();
    }

    /* Ролик на экране: у текста героя уходит описание (класс героя), а кадр
       под роликом приглушается (класс слоя кадра — волна 3, слой отдельный). */
    function markTrailer(on) {
      if (!state) return;
      try {
        state.node.toggleClass('lumen-hero--trailer', !!on);
        state.stage.toggleClass('lumen-hero-stage--trailer', !!on);
      } catch (e) { }
    }

    /* Проверка на ТВ 2026-09-24: смена кадров стоит, пока ролик РЕАЛЬНО
       играет (onStart плеера), и продолжается, когда он кончился или
       снят. Пауза у контроллера слайдшоу одна на все причины, поэтому
       снимается только тогда, когда не держат и другие (slidesHeld). */
    function trailerOn() {
      if (!state) return;
      state.trailerOn = true;
      if (state.slides) {
        try { state.slides.pause(); } catch (e) { warn('hero: slides pause failed', e); }
      }
    }

    function trailerOff() {
      if (!state || !state.trailerOn) return;
      state.trailerOn = false;
      if (state.slides && !slidesHeld()) {
        try { state.slides.resume(); } catch (e) { warn('hero: slides resume failed', e); }
      }
    }

    /* Причины паузы смены кадров: ролик играет (trailerOn), фокус в рядах
       (compact), главная под другим экраном (parked) и — ревью правок
       волны 3, п.7 — фокус на другой карточке, чем показанная (focusAway):
       до этой правки смену показанного фильма снимал только show()
       следующей, и до него она тикала — на стенде кадр «Обители зла»
       сменился через 193 мс после ухода фокуса. Держит хоть одна —
       resume() не зовётся. */
    function slidesHeld() {
      return !!(state && (state.trailerOn || state.compact || state.parked || focusAway()));
    }

    /* Запрос роликов. Языков два, как у штатной Lampa (tmdb.js videos,
       API_NOTES_2 §2): сначала язык интерфейса, и только если на нём ничего
       не нашлось — английский. Оба ответа кэшируются Lampa на неделю.
       Отменить запрос нечем: Lampa.Api.sources.tmdb.get ничего не
       возвращает (get$c, vendor/lampa/app.min.js:19693-19737). Поздний ответ
       отсекает tgen — его поднимает cancelTrailer(), а её зовут смена
       карточки в фокусе (onFocus), смена настройки автотрейлера
       (applyTrailer), park() и unmount(); ответ, доехавший до снятого
       героя, отсекает ещё и isMounted(). */
    /* Ревью H1: у запроса роликов свой срок, VIDEOS_LIMIT на каждый язык.
       network.clear() Lampa выбрасывает колбэки запроса, и ответа не будет
       никогда (разбор у send в src/58_prefetch.js) — план висел без исхода,
       HUD залипал на «plan». Срок — тот же исход, что ошибка: следующий
       язык или «err req». Один исход на язык (over): поздний ответ после
       срока ничего не заводит. Таймер — state.videosTimer, его снимает
       cancelTrailer (а с ней — park и unmount). */
    function loadTrailer(card, captured) {
      var media = mediaOf(card);
      var lang = langCode();

      function ask(code, next) {
        var over = false;
        function fail() {
          if (over) return;
          over = true;
          if (tgen !== captured || !state) return;
          stopTimer('videosTimer');
          if (next) ask(next, '');
          else planDone('err req');
        }
        try {
          if (!window.Lampa || !Lampa.Api || !Lampa.Api.sources || !Lampa.Api.sources.tmdb) { planDone('stop'); return; }
          stopTimer('videosTimer');
          state.videosTimer = setTimeout(function () {
            if (state && tgen === captured) state.videosTimer = null;
            fail();
          }, VIDEOS_LIMIT);
          Lampa.Api.sources.tmdb.get(
            media + '/' + card.id + '/videos',
            { langs: code },
            function (json) {
              if (over) return;
              over = true;
              if (tgen !== captured || !state) return;
              stopTimer('videosTimer');
              if (!isMounted()) { planDone('stop'); return; }
              var video = null;
              try {
                if (LC.trailer && typeof LC.trailer.pickTrailer === 'function') video = LC.trailer.pickTrailer(json && json.results);
              } catch (ePick) {
                warn('hero: trailer pick failed', ePick);
              }
              if (video && video.key) { startTrailer(video.key, captured); return; }
              if (next) ask(next, '');
              else {
                planDone('');
                trailerNote('none');
              }
            },
            fail,
            { life: VIDEOS_LIFE }
          );
        } catch (e) {
          warn('hero: trailer request failed', e);
          over = true;
          if (tgen === captured) {
            stopTimer('videosTimer');
            planDone('err req');
          }
        }
      }

      ask(lang, lang === 'en' ? '' : 'en');
    }

    function startTrailer(key, captured) {
      var handed = false;
      try {
        if (tgen !== captured || !state) return;
        if (!isMounted()) { planDone('stop'); return; }
        if (!trailerReady()) { planDone('stop'); return; }
        if (trailerBlocked()) { planDone('stop'); forgetTrailerFocus(); return; }
        if (!LC.trailer || typeof LC.trailer.player !== 'function') { planDone('stop'); return; }
        var host = state.stage.find('.lumen-hero__trailer');
        if (!host || !host.length) { planDone('stop'); return; }
        planDone('');
        handed = true;
        /* Класс ставится по ФАКТУ старта (onStart плеера), а не по его
           созданию: ролик может не заиграть вовсе (нет сети, YouTube
           недоступен), и тогда герой обязан остаться как был. */
        state.trailer = LC.trailer.player(host, key, function () {
          if (tgen !== captured || !state) return;
          markTrailer(true);
          trailerOn();
        }, function () {
          if (tgen !== captured || !state) return;
          state.trailer = null;
          markTrailer(false);
          trailerOff();
        });
      } catch (err) {
        warn('hero: trailer start failed', err);
        /* Ревью волны 1b, п.5: план уже отдан плееру, а тот бросил — HUD
           остался бы на «plan» или на «api» недоделанного плеера. Номер
           плана к этому мигу мог устареть (плеер заводит свой —
           src/55_trailer.js), поэтому «stop» без номера: между planDone('')
           и исключением владельцем мог стать только этот плеер. */
        if (handed) trailerNote('stop');
        else planDone('stop');
      }
    }

    /* Отложенный старт для карточки, на которой остановился фокус. Сторож
       тот же, что у акцента: state.pending меняется на каждом фокусе, поэтому
       тик, доехавший после перевода фокуса, выходит первой же строкой. */
    function scheduleTrailer(card) {
      if (!trailerReady()) return;
      state.trailerPlan = trailerNote('plan');
      var captured = tgen;
      state.trailerTimer = setTimeout(function () {
        if (!state || tgen !== captured) return;
        state.trailerTimer = null;
        if (state.pending !== card || !isMounted()) { planDone('stop'); return; }
        /* Настройку и режим анимаций перечитываем в момент старта: за восемь
           секунд их могли поменять. */
        if (!trailerReady()) { planDone('stop'); return; }
        if (trailerBlocked()) { planDone('stop'); forgetTrailerFocus(); return; }
        loadTrailer(card, captured);
      }, TRAILER_DELAY);
    }

    /* Настройка lumen_hero_trailer переключена на лету: выключение снимает
       играющий ролик, включение ничего не запускает — ролик появится со
       следующей остановки фокуса. Ту же функцию зовёт applyMotion. */
    function applyTrailer() {
      if (!state) return;
      if (trailerReady()) return;
      cancelTrailer();
    }

    /* ------------------------------------------------------------------ */
    /* «Несколько кадров»: кадры фильма в герое сменяют друг друга.        */
    /* С 2026-09-24 — и в «Кадры и трейлер» тоже, пока ролик не играет      */
    /* (slidesAllowed, trailerOn/trailerOff выше).                          */
    /*                                                                     */
    /* Механика слайдшоу — общая с карточкой: отбор кадров                  */
    /* LC.backdrops.pickBackdrops (без текста на кадре, широкие вперёд,     */
    /* главный первым, не больше LC.slideshow.maxFramesFor(режим): lite 4,  */
    /* full 8, off 1 — то есть в 'off' ротации нет вовсе) — у героя без     */
    /* явно отвергнутых на TMDB кадров (slideFrames), — ритм и пауза —      */
    /* LC.slideshow.create в режиме opts.show (src/51_slideshow.js). Показ  */
    /* остаётся за героем: тот же loadFrame/swapFrame, что у смены          */
    /* карточки, — decode() до показа, сторож поколения, в лёгком режиме и  */
    /* без тяжёлых эффектов смена в одном слое, мгновенно, без кроссфейда.  */
    /*                                                                     */
    /* Данные — из деталей, которые герой и так берёт на каждую карточку:   */
    /* append_to_response=images (detailsRequest) приносит images.backdrops */
    /* тем же ответом, что и логотипы; лишнего запроса нет.                 */
    /*                                                                     */
    /* Память. Кадр w1280 — 3 686 400 байт растра. Одновременно живут не   */
    /* больше двух: показанный и следующий, который предзагрузчик           */
    /* loadFrame тянет только в момент тика (заранее не держим ничего).     */
    /* С тяжёлыми эффектами кадр сменяется кроссфейдом двух слоёв, и        */
    /* ушедший слой держал бы свой кадр до следующей смены — поэтому после  */
    /* кроссфейда его src снимается (freeHidden).                           */
    /*                                                                     */
    /* Интервал — общий с карточкой, «Интервал смены кадров» (LC.backdrops. */
    /* intervalMs, по умолчанию 14 с): одна ручка на «как часто меняются    */
    /* кадры» во всём плагине. 14 с пользователь уже видит в карточке и не  */
    /* жаловался; это больше задержки автотрейлера (8 с), то есть первая    */
    /* смена случается, когда человек заведомо уже прочёл название и мету,  */
    /* и в лёгком режиме, где смена — резкий срез без перехода, четыре      */
    /* кадра проходят круг за минуту, а не мелькают.                        */
    /*                                                                     */
    /* Пауза: фокус в рядах ниже первого (setCompact) — как частицы; фокус */
    /* на другой карточке, чем показанная (onFocus, до её show()); уход с   */
    /* главной вглубь паркует героя (park: pause, номер кадра сохраняется), */
    /* снятие героя (unmount) уничтожает слайдшоу; экран, накрытый заставкой,*/
    /* и главная под открытой карточкой — тиков не делают (проверки самого  */
    /* контроллера). Смена карточки уничтожает слайдшоу в show() до того,   */
    /* как поднимется gen, — от прошлой карточки не остаётся ни таймера.    */
    /* ------------------------------------------------------------------ */

    var SLIDE_FREE = 700;

    /* Проверка на ТВ 2026-09-24: и в «Несколько кадров», и в «Кадры и
       трейлер» (heroMedia выше) — смену запрещает только режим «Выкл».
       В 'trailer' её на время ролика держит пауза (trailerOn). */
    function slidesAllowed() {
      return !benchHeld && motionMode() !== 'off';
    }

    function slideInterval() {
      try {
        if (LC.backdrops && typeof LC.backdrops.intervalMs === 'function') return LC.backdrops.intervalMs();
      } catch (e) { }
      return 14000;
    }

    function cancelSlides() {
      if (!state) return;
      stopTimer('slideFree');
      if (state.slideLook) {
        state.slideLook.cancel();
        state.slideLook = null;
      }
      if (state.slides) {
        var s = state.slides;
        state.slides = null;
        try { s.destroy(); } catch (e) { warn('hero: slides destroy failed', e); }
      }
    }

    /* Кроссфейд с тяжёлыми эффектами идёт двумя слоями (swapFrame), и
       ушедший слой, погаснув, держит свой кадр до следующей смены. Здесь он
       его отпускает — после перехода (.4s в src/30_css.js, с запасом). */
    function freeHidden(captured) {
      if (!state || !fxHeavy()) return;
      stopTimer('slideFree');
      state.slideFree = setTimeout(function () {
        if (gen !== captured || !state) return;
        state.slideFree = null;
        try {
          var layers = [state.stage.find('.lumen-hero__bg--a'), state.stage.find('.lumen-hero__bg--b')];
          for (var i = 0; i < layers.length; i++) {
            if (!layers[i].hasClass('is-active')) layers[i].removeAttr('src');
          }
        } catch (e) { }
      }, SLIDE_FREE);
    }

    function startSlides(model, captured) {
      /* Запаркованный герой (уход вглубь, park ниже) слайдшоу не заводит:
         настройку могли переключить из карточки, и тогда смена кадров
         стартует на возврате — resume зовёт applyMotion. */
      if (!state || state.slides || gen !== captured || state.parked) return;
      if (!slidesAllowed() || !state.details || !model || !model.backdrop) return;
      if (!LC.slideshow || !LC.backdrops) return;
      try {
        /* Волна 3: круг начинается с кадра, который на экране (выбран
           startFrame; до выбора — heroBackdrop модели), а ключевой арт
           (backdrop_path) в ротацию героя не идёт, если на экране не он:
           иначе через интервал на месте героя снова стоял бы постер ряда.
           Карточке фильма ротацию это не меняет — у неё свой вызов
           pickBackdrops (src/50_backdrops.js). */
        var main = state.framePath || model.backdrop;
        var keyArt = state.details.backdrop_path || (state.shownCard && state.shownCard.backdrop_path) || '';
        var images = state.details.images;
        /* Ревью правок раунда хвостов, п.5: в круг идут все кадры, кроме
           явно отвергнутых на TMDB (slideFrames; до этой правки — только
           годные для первого кадра, goodFrames, и у многих фильмов круга не
           было вовсе). Кадр на экране pickBackdrops ставит первым сам;
           остался он один — смены кадров нет. */
        /* Волна «хвосты героя», п.C2: и в смене кадров — не копия постера.
           Кадр, про который уже известно, что он похож на постер (ответ
           сравнения первого кадра, chooseFrame), в круг не идёт вовсе. */
        var poster = model.poster || '';
        var look = poster ? LC.thumbs : null;
        var list = LC.util.filter(slideFrames(images && images.backdrops), function (b) {
          if (look && b.file_path !== main && look.verdict(poster, b.file_path) === true) return false;
          return !keyArt || keyArt === main || b.file_path !== keyArt;
        });
        var paths = LC.backdrops.pickBackdrops({ backdrops: list }, main, LC.slideshow.maxFramesFor(motionMode()));
        if (!paths || paths.length <= 1) return;
        var slideShow = function (path, done) {
          loadFrame({ backdrop: path }, captured, function (ok) {
            if (ok) freeHidden(captured);
            done(ok);
          }, true);
        };
        state.slides = LC.slideshow.create(state.node, paths, {
          enabled: slidesAllowed,
          intervalMs: slideInterval,
          show: function (path, done) {
            /* Прошлый кадр ещё едет (медленная сеть) — тик пропускаем, не
               заводя второго предзагрузчика: кадров в памяти не больше двух.
               Ревью tails4, п.6: главная спрятана под поиском, SearchInput
               или «Расширениями» (homeHidden) — кадр никто не увидит, тик
               тоже пропускаем (на стенде — две загрузки w1280 за 20 с).
               Очередь контроллера стоит на месте, и после закрытия смена
               идёт с того же кадра. */
            if (gen !== captured || !state || state.loader || state.slideLook || homeHidden()) return;
            /* П.C2: ответа про этот кадр ещё нет — сперва сравнение с
               постером (фокус стоит — смена идёт только в покое), и только
               потом загрузка w1280. Похож — кадр помечается битым
               (done(false)) и больше не предлагается; контроллер сразу
               пробует следующий. Пока шло сравнение, что-то сменилось
               (фокус ушёл, парковка, ролик, главная спрятана, едет кадр) —
               тик пропускается, ответ уже в памяти для следующего. */
            var v = look ? look.verdict(poster, path) : false;
            if (v === true) { done(false); return; }
            if (v !== undefined) { slideShow(path, done); return; }
            /* Ревью раунда героя (d97cffc), п.1: ответ бывает синхронным
               (память, блокировка модуля) — тогда колбэк уже отработал, и
               его дескриптор в state.slideLook не пишется: иначе мёртвый
               дескриптор навсегда закрывал бы тики смены кадров гардом
               выше. */
            var answered = false;
            var job = look.compare(poster, path, function (similar) {
              answered = true;
              if (!state || gen !== captured) return;
              state.slideLook = null;
              if (state.loader || homeHidden() || slidesHeld()) return;
              if (similar === true) { done(false); return; }
              slideShow(path, done);
            });
            if (!answered) state.slideLook = job;
          }
        });
        if (slidesHeld()) state.slides.pause();
        state.slides.activate();
      } catch (e) {
        warn('hero: slides failed', e);
      }
    }

    /* Настройка или режим анимаций сменились на лету. Запрещено — слайдшоу
       снимается сразу; разрешено — заводится по уже загруженным деталям
       карточки под фокусом, без нового запроса. */
    function applySlides() {
      if (!state) return;
      if (!slidesAllowed()) { cancelSlides(); return; }
      if (!state.slides && state.model && state.details) startSlides(state.model, gen);
    }

    /* Ревью «Волны 1», п.5: «Интервал смены кадров» сменили на лету —
       идущую смену перезаводим (resume контроллера читает intervalMs
       заново). Стоящую на паузе — ролик, сжатие, парковка, фокус на другой
       карточке (slidesHeld) — не будим: её снимет своя причина, и тот же
       resume возьмёт уже новый интервал. */
    function applyInterval() {
      if (!state || !state.slides) return;
      if (slidesHeld()) return;
      try {
        state.slides.pause();
        state.slides.resume();
      } catch (e) {
        warn('hero: slides interval failed', e);
      }
    }

