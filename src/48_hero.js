    /* Task 71: предзагрузка логотипа. Отзыв пользователя 2026-09-21, п.2:
       «названия подгружают на ходу „постеры“ названия». Логотип ставился
       фоном сразу, как только приходили детали, и класс прятал заголовок
       ещё до того, как картинка доезжала, — на экране название сначала
       пропадало, а потом появлялось картинкой.

       Критерий «байты доехали» тот же, что у кадра: onload, а на таймауте
       — complete && naturalWidth. decode() здесь НЕ ждём намеренно: в
       скрытой вкладке Chromium картинки не растеризует и промис не
       резолвится вовсе (замер координатора на стенде 2026-09-21, тот же
       урок, что у кадра в loadFrame), а логотип — мелкая картинка, ради
       которой заводить вторую страховку незачем.

       Приоритета у запроса нет намеренно: высокий стоит у кадра героя
       (fetchPriority = 'high' в loadFrame), и логотип обязан ехать после
       него — кадр занимает весь экран, логотип помещается в строку. */
    function loadLogo(path, url) {
      var captured = gen;
      state.logoLoader = preloadLogo(path, url, function (ok) {
        if (gen !== captured || !state || !isMounted()) return;
        state.logoLoader = null;
        /* Правка 2026-09-22: ожидание заголовка кончилось — исход логотипа
           известен. Неудача выводит текст немедленно, не дожидаясь потолка
           TITLE_WAIT (см. writeTitle); удача снимает потолок, потому что
           показывать текст уже незачем — его прячет .lumen-hero--logo. */
        if (!ok) {
          if (state.model && state.model.logo === path) forceTitleText();
          return;
        }
        stopTimer('titleTimer');
        /* Пока картинка ехала, модель могла смениться дорисовкой деталей
           той же карточки (render(model, false)) — логотип ставим только
           тому названию, которое его и просило. */
        if (!state.model || state.model.logo !== path) return;
        showLogo(state.node, url);
      });
    }

    /* Адрес логотипа — ОДИН на героя и карточку фильма (правка 2026-09-23).
       Размер выбирается по рамке героя (41.62 em Lampa — самая широкая
       рамка, в которой логотип вообще рисуется; у карточки она не шире,
       см. cardLogoBox), и карточка берёт тот же адрес намеренно: исход
       загрузки кэшируется по пути (logoSeen), и «уже доехал» обязано
       значить «лежит в кэше браузера ровно по этому адресу». Живая проверка
       первого варианта с собственным размером карточки (w500 против w780 у
       героя на 960×540@2) показала оба дефекта разом: логотип, уже
       виденный в герое, качался второй раз, а известный исход ставил в
       рамку картинку, которой в кэше ещё не было, — рамка на миг пустела.
       Второй аргумент emPx — масштаб интерфейса плагина. Здесь он ровно 1:
       lumen_scale до текста героя не доходит (см. LOGO_EM выше). */
    function logoUrl(path) {
      return path ? imageUrl(path, logoSizeFor(LC.util.emPx(LOGO_EM * TEXT_ZOOM, 1))) : '';
    }

    /* Ставит логотип текущей модели: известный — сразу, неизвестный (и
       неудавшийся один раз, см. 'retry' выше) — после предзагрузки,
       отсутствующий, выключенный настройкой и дважды неудавшийся —
       никогда. Зовётся из write(), то есть на каждой перерисовке героя.

       Правка 2026-09-22: возвращает исход, по которому write() решает, что
       делать с текстовым заголовком:
         'logo' — логотип уже на экране, текст не нужен вовсе;
         'none' — логотипа не будет (нет в модели, выключен настройкой,
                  дважды не доехал) — текст;
         'wait' — картинка поехала, исход будет позже. */
    function applyLogo(node, model) {
      var path = logoAllowed() ? model.logo : null;
      /* Предыдущая предзагрузка больше не нужна: её исход относится к
         другому названию, а сторож поколения её колбэк уже не пустит. */
      if (state.logoLoader) {
        state.logoLoader.cancel();
        state.logoLoader = null;
      }
      var url = logoUrl(path);
      if (!url || logoSeen[path] === 'fail') { hideLogo(node); return 'none'; }
      if (logoSeen[path] === 'ok') { showLogo(node, url); return 'logo'; }
      hideLogo(node);
      loadLogo(path, url);
      return 'wait';
    }

    /* Правка 2026-09-22 по отзыву пользователя («все равно переключение
       названий есть, выглядит не оч»): вывод заголовка ОДИН — либо текст,
       либо логотип, без видимой подмены первого вторым.

       Что было на экране до правки. write() писала текст всегда, а логотип
       вставал позже — по onload своей картинки (applyLogo → loadLogo).
       Замер на живой Lampa (стенд localhost:8766, главная, шесть карточек
       ряда подряд, кэш картинок сброшен cache-busting'ом) — сколько
       миллисекунд текстовый заголовок был виден до подмены на логотип:
       полный режим движения 108, 110, 54, 54, 46, 73 мс; лёгкий — 61, 67,
       52, 58, 45, 374 мс. SWAP_MS этого не лечил: он откладывает весь вывод
       разом, а не ждёт логотип.

       Теперь место заголовка остаётся ПУСТЫМ, пока исход логотипа неизвестен:
         - деталей ещё нет (model.pending) — логотип приходит только с ними,
           и до ответа неизвестно даже, есть ли он у фильма;
         - картинка логотипа едет ('wait' от applyLogo).
       Мета и описание при этом выводятся как обычно — пустует только строка
       названия. Скачка раскладки от этого нет: высота .lumen-hero__title
       фиксированная (height:1.29em, src/30_css.js), пустой он занимает ровно
       столько же места.

       Потолок ожидания TITLE_WAIT = 600 мс. Дольше держать название пустым
       нельзя: на медленной сети логотип может не доехать вовсе, а пустое
       место вместо имени фильма хуже подмены. 600 мс с запасом покрывают и
       самый долгий логотип из замеров выше (374 мс), и путь «ответ деталей
       плюс логотип» (ответы деталей на том же стенде — 41, 47, 49, 51, 148,
       157, 247 мс).

       Отдельного сторожа у ожидания нет намеренно: отмену при быстром
       листании делает тот же gen, что у отсрочки swapTimer, — фокус ушёл,
       gen вырос, отложенный вывод чужого названия отброшен.

       Настройка «Логотип названия» выключена — ждать нечего: logoAllowed()
       ложно, applyLogo возвращает 'none', текст выводится сразу. */
    function writeTitle(model, logoState) {
      /* Ждём, пока логотип едет, и пока не пришли детали, которые только и
         могут его принести. Второе — лишь при включённой настройке: иначе
         логотипа не будет в любом случае. */
      var waiting = logoState === 'wait' || (logoState === 'none' && model.pending && logoAllowed());
      if (waiting && !state.titleForced) {
        state.node.find('.lumen-hero__title').text('');
        startTitleTimer();
        return;
      }
      stopTimer('titleTimer');
      /* Логотип на экране — текст под ним не пишем вовсе: .lumen-hero--logo
         его и так прячет, но пустой узел честнее показывает, что видимого
         вывода названия текстом не было. */
      state.node.find('.lumen-hero__title').text(logoState === 'logo' ? '' : model.title);
    }

    /* Потолок ожидания. Сторож — gen: ушедший дальше фокус поднимает его в
       show(), и вывод названия прошлой карточки не случится. */
    function startTitleTimer() {
      if (state.titleTimer) return;
      var captured = gen;
      state.titleTimer = setTimeout(function () {
        if (gen !== captured || !state) return;
        state.titleTimer = null;
        forceTitleText();
      }, TITLE_WAIT);
    }

    /* Ждать больше нечего (потолок истёк или логотип не доехал): выводим
       текст и запоминаем это решение до следующей карточки — иначе
       дорисовка деталей той же карточки (render(model, false)) снова увела
       бы название в пустоту. */
    function forceTitleText() {
      if (!state) return;
      stopTimer('titleTimer');
      state.titleForced = true;
      if (state.model) state.node.find('.lumen-hero__title').text(state.model.title);
    }

    /* Записывает модель в узлы. swap=true — смена карточки, иначе это
       дорисовка деталей той же карточки: она обязана быть без анимации,
       иначе герой дёргался бы дважды на каждую карточку.

       Найдено живьём (первый круг Task 18): write() обязана брать модель из
       state.model, а не из замыкания. Ответ деталей из кэша Lampa приходит
       СИНХРОННО, ещё до того как сработает отложенная на 180 мс подмена
       текста, — и та возвращала на экран модель без деталей: мета съезжала
       обратно на голый год, а скелетон загорался навсегда.

       Task 71: смена карточки откладывает вывод на SWAP_MS во ВСЕХ режимах,
       а не только в full. В full отсрочка была всегда — под анимацию ухода
       текста, — и ровно из-за неё «первая версия работала идеально»: детали
       уже виденной карточки Lampa отдаёт из кэша синхронно, отложенный
       write() берёт модель уже с логотипом, и видимый вывод один. В lite
       write() был мгновенным, и выводов было два: сначала текст, потом
       логотип — отзыв пользователя 2026-09-21, п.2 («названия подгружают на
       ходу „постеры“ названия»). Цена — те же 180 мс задержки текста при
       листании, которые в full и так есть; анимации ухода текста в lite/off
       по-прежнему нет, только отсрочка. */
    function render(model, swap) {
      if (!state || !model) return;
      var node = state.node;
      state.model = model;

      function write() {
        if (!state || !state.model) return;
        /* Отложенный вывод, если он ещё не сработал, больше не нужен: эта
           запись новее, а второй проход по тем же узлам ничего не добавит. */
        stopTimer('swapTimer');
        var current = state.model;
        var text = node.find('.lumen-hero__text');
        /* Task 43: рейтинг идёт последним элементом той же строки —
           «2026 · 1:40 · драма · ★ 8.1». Отдельного чипа под него больше нет:
           одна строка muted спокойнее, чем строка плюс плашка, и это ровно
           та же склейка, что в подписи карточки ряда — «2017 · ★ 6.4»
           (src/62_badges.js, decorate).
           Склейка живёт здесь, а не в heroModel: модель собирает мету по
           частям и дополняет её, когда приходят детали (сезоны, жанры), а
           оценка известна сразу из карточки ряда — приклей её в модели, и
           она оказалась бы в середине строки, между годом и жанрами. */
        var metaLine = current.rating ? current.meta.concat(['★ ' + current.rating]) : current.meta;
        node.find('.lumen-hero__meta').text(metaLine.join(' · '));
        node.find('.lumen-hero__descr').text(current.overview);
        node.find('.lumen-hero__status').text(current.status);
        node.toggleClass('lumen-hero--status', !!current.status);
        node.toggleClass('lumen-hero--pending', !!current.pending);
        /* Скелетон описания нужен, только если описания нет вовсе: в данных
           ряда overview обычно уже есть, и плашки поверх готового текста
           были бы ложным «грузится» (ограничение брифа 3). */
        node.toggleClass('lumen-hero--nodescr', !current.overview);

        /* Task 71: логотип ставится не здесь, а после того как его картинка
           доехала (applyLogo → loadLogo). Размер при этом задаётся сразу по
           пропорции из модели: узел до показа скрыт (display:none у
           .lumen-hero__logo), и раскладку эти две величины не двигают. */
        var logoState = applyLogo(node, current);
        applyLogoBox();
        /* Правка 2026-09-22: заголовок пишется ПОСЛЕ логотипа — его вывод
           зависит от исхода логотипа (writeTitle). */
        writeTitle(current, logoState);

        text.removeClass('is-swapping');
        if (motionMode() === 'full') text.addClass('is-in');

        /* Волна 3: текст нового фильма выведен — с этого мига кадр
           прошлого под ним живёт не дольше HOLD_MS (holdFrame). Отсчёт от
           вывода, а не от show(): текст выходит через SWAP_MS или сразу
           (детали из кэша), и отсрочка вывода остаётся кадру нового
           фильма — доехав за неё, он встаёт без заглушки, одной сменой.
           Ревью волны 3, п.1: фокус к выводу текста уже ушёл на другую
           карточку — отсчёт не заводим, он ждёт возврата фокуса (onFocus). */
        if (state.holdDue && !focusAway()) {
          state.holdDue = false;
          armHold();
        }
      }

      if (!swap) {
        write();
        return;
      }

      /* Анимация ухода текста — только в полном режиме: правила .is-swapping
         (opacity:0) и .is-in (кадр появления) заведены под .lumen-motion-full
         (src/30_css.js, блок текста героя), и в lite/off тот же класс
         означал бы мгновенно спрятанный и мгновенно показанный текст. */
      if (motionMode() === 'full') node.find('.lumen-hero__text').removeClass('is-in').addClass('is-swapping');
      var captured = gen;
      stopTimer('swapTimer');
      state.swapTimer = setTimeout(function () {
        if (gen !== captured || !state) return;
        state.swapTimer = null;
        write();
      }, SWAP_MS);
    }

    /* Кроссфейд кадра: новый URL грузится в скрытый слой, и только после
       onload слои меняются местами. Пока кадр не пришёл, на экране остаётся
       предыдущий: при листании фон не мигает (ограничение брифа 1). Когда
       фокус остановился, кадр прошлого фильма под новым текстом держится не
       дольше HOLD_MS — дальше заглушка, постер карточки из ряда (holdFrame);
       её ставит эта же функция.

       Task 40: при выключенных тяжёлых эффектах второй полноэкранный слой не
       используется вовсе — кадр подменяется в том, что уже показан. Кроссфейд
       героя это две картинки во весь экран одновременно: пока идёт переход
       (transition:opacity .6s у .lumen-hero__bg, src/30_css.js), композитор
       держит оба слоя, а фокус на главной переезжает каждые несколько секунд.
       Правило transition в таблице стилей тоже стоит под body.lumen-fx-heavy,
       поэтому подмена здесь мгновенная, без полупрозрачности.

       Task 64: слой — <img>, поэтому кадр ставится атрибутом src, а не
       background-image. Второго сетевого запроса это не добавляет: тот же
       адрес только что дотянул предзагрузчик из loadFrame, и <img> берёт его
       из кэша ресурсов. Порядок тот же, что и был: src ставится ТОЛЬКО
       здесь, то есть уже после того, как байты доехали (а при живом decode()
       — и после декодирования), поэтому смена src не показывает пустой
       слой. */
    function swapFrame(url, blur) {
      if (!state) return;
      var a = state.stage.find('.lumen-hero__bg--a');
      var b = state.stage.find('.lumen-hero__bg--b');
      var activeIsA = a.hasClass('is-active');
      if (!fxHeavy()) {
        /* Слой, который уже на экране; на первом кадре карточки активного
           ещё нет — тогда это всегда --a, и --b остаётся пустым навсегда. */
        var only = activeIsA ? a : (b.hasClass('is-active') ? b : a);
        only.attr('src', url);
        only.addClass('is-active');
        only.toggleClass('lumen-hero__bg--blur', !!blur);
        state.frameUrl = url;
        return;
      }
      var next = activeIsA ? b : a;
      var prev = activeIsA ? a : b;
      next.attr('src', url);
      next.addClass('is-active');
      prev.removeClass('is-active');
      /* Метку получает ТОЛЬКО приходящий слой, и только он. С уходящего её
         не снимают намеренно: в этот момент он ещё непрозрачен — переход
         opacity .6s только начинается (src/30_css.js, .lumen-hero__bg под
         body.lumen-fx-heavy), — а наезд снялся бы мгновенно и без перехода,
         и зритель первые сотни миллисекунд видел бы размытый постер,
         скачком ужавшийся на 10 %. Это ровно та жалоба, которую Task 52
         лечит, только перенесённая на уходящий слой. Состояние от этого не
         портится: когда этот слой станет приходящим, toggleClass выставит
         ему метку заново — по его собственному кадру. */
      next.toggleClass('lumen-hero__bg--blur', !!blur);
      state.frameUrl = url;
    }

    /* Task 64: подложку LQIP держат до первого ПОКАЗАННОГО кадра — дальше
       она лежит под непрозрачной картинкой и стоит только памяти.
       Освобождение отложено: кадр проявляется переходом opacity (до 600 мс у
       кроссфейда с тяжёлыми эффектами), и снять подложку в тот же миг
       значило бы показать сквозь полупрозрачный кадр голый фон. 900 мс —
       этот максимум плюс запас.
       Отсюда и честная форма утверждения о памяти: 202 800 байт подложки
       живут от начала её загрузки до 900 мс ПОСЛЕ показа кадра, то есть всё
       время, пока едет w1280, плюс эти 900 мс. Если кадр не доехал вовсе
       (onerror, таймаут без байтов), эта функция не зовётся и подложка
       остаётся на экране до следующего показанного кадра или до unmount —
       так и задумано: пустой герой хуже размытого.
       removeAttr, а не src = '': пустой src в старых движках это запрос к
       адресу самой страницы. */
    var LQIP_FREE = 900;
    function releaseLqip() {
      if (!state || !state.lqipUrl) return;
      var captured = gen;
      stopTimer('lqipTimer');
      state.lqipTimer = setTimeout(function () {
        if (gen !== captured || !state) return;
        state.lqipTimer = null;
        state.lqipUrl = '';
        try {
          var lqip = state.stage.find('.lumen-hero__lqip');
          lqip.removeClass('is-active');
          lqip.removeAttr('src');
        } catch (e) {}
      }, LQIP_FREE);
    }

    /* Предзагрузка кадра фокусной карточки. Кадра нет — берём постер и
       помечаем слой для размытия (экран 22 брифа: композиция не меняется).
       Тот же URL повторно не грузится.

       Режим анимаций 'off' кадр НЕ обновляет вовсе (таблица рисков плана:
       «в режиме motion off герой не обновляет кадр, только текст»). Гейт
       стоит до new Image(): в 'off' дорога не плавность смены слоёв (её и
       так гасит CSS), а сама загрузка и декодирование большого кадра —
       w1280/original на каждую остановку фокуса, поверх кадра, который
       параллельно тянет сама Lampa через Background.change. Пользователь
       слабого ТВ выбирает 'off' именно ради этого. */
    /* done(ok) — необязательный: его передаёт слайдшоу «Несколько кадров»
       (startSlides), чтобы знать, показан ли кадр. Зовётся только для живого
       поколения; кадр, уже стоящий на экране, считается показанным.
       slide — кадр смены кадров (startSlides), а не кадр показа. */
    function loadFrame(model, captured, done, slide) {
      if (!state) return;
      if (motionMode() === 'off') return;
      var blur = false;
      var path = model.backdrop;
      if (!path) { path = model.poster; blur = true; }
      if (!path) return;

      /* Task 38: у «размытого» варианта размер намеренно крошечный. Блюр
         фильтром снят (src/30_css.js, .lumen-hero__bg--blur), и мягкость теперь
         даёт сам апскейл: w92 — 92 px по ширине, растянутые cover на весь
         кадр героя, то есть больше чем в двадцать раз. Заодно это самый
         дешёвый кадр, который герой вообще грузит. */
      var url = imageUrl(path, blur ? 'w92' : sizeFor(screenWidth()));
      if (url && url === state.frameUrl && done) { done(true); return; }
      if (!url || url === state.frameUrl) return;

      /* Task 64: LQIP — тот же backdrop в w300. Слой под кадрами, показ без
         ожидания: у кадра 16:9 это 300 × 169, то есть 0.05 Мпикс и 202 800
         байт растра (naturalWidth × naturalHeight × 4, прочитано на живом
         стенде 2026-09-21 на кадре /1CIaRYKf3zg2Xyce1CSfCMg2Vfw.jpg; высота
         зависит от пропорции кадра, TMDB масштабирует по ширине). Доезжает
         и декодируется он заметно раньше w1280 — у того 1280 × 720 и
         3 686 400 байт.
         Условие показа — «на экране ещё нет НИ ОДНОГО кадра»: state.frameUrl
         заполняется в swapFrame, то есть в момент показа. Обычно это ровно
         один раз, на первой карточке под фокусом. Но если фокус успел уйти
         раньше, чем доехал w1280, подложка переедет на новую карточку вместе
         с кадром — и это правильнее, чем держать под пустым экраном кадр
         фильма, с которого фокус уже ушёл; лишний запрос w300 ограничен той
         же задержкой DELAY, что и сам кадр (при листании без остановок не
         уходит ни одного).
         После первого показанного кадра подложка не обновляется вовсе: под
         приходящим кадром лежит непрозрачный предыдущий (фон при смене
         карточки не мигает — ограничение брифа 1), и подложки из-под него не
         видно.
         Варианту «кадра нет, собираем из постера» подложка не нужна вовсе:
         постер и так берётся в w92, что мельче w300. */
      if (!blur && !state.frameUrl) {
        var small = imageUrl(path, 'w300');
        if (small) {
          var lqip = state.stage.find('.lumen-hero__lqip');
          lqip.attr('src', small);
          lqip.addClass('is-active');
          state.lqipUrl = small;
          /* Волна 3: подложка — уже кадр этого фильма (holdFrame). */
          state.frameId = state.shownId;
        }
      }

      var report = typeof done === 'function' ? done : function () {};
      var loader = new Image();
      /* Task 39: просим WebView не декодировать кадр синхронно на главном
         потоке (свойство decoding, Chrome 65+; движки постарше его просто
         игнорируют). Ставится ДО src: подсказка читается в момент, когда
         загрузка начинается. Так же помечены все остальные предзагрузчики
         плагина — фон карточки, слайдшоу, рулетка. */
      loader.decoding = 'async';
      /* Task 64: тот же высокий приоритет, что и у слоя кадра в разметке —
         запрос делает именно этот предзагрузчик, поэтому подсказка нужна
         здесь. Свойство fetchPriority есть с Chrome 101; на движках постарше
         присваивание просто создаёт неиспользуемое поле объекта и ничего не
         меняет. */
      loader.fetchPriority = 'high';
      var done = false;
      /* Task 47: decode() есть с Chrome 64 (ресёрч §4); на движках постарше
         остаётся прежний путь через onload. */
      var decoding = typeof loader.decode === 'function';

      /* Байты кадра доехали? Единственный признак, которому можно верить,
         когда decode() отвергнут или не доехал вовсе: complete значит
         «загрузка завершилась», naturalWidth > 0 — «завершилась картинкой,
         а не ошибкой». */
      function loaded() {
        return !!(loader.complete && loader.naturalWidth);
      }

      /* Уборка стоит ЗА гардом поколения намеренно: stopTimer работает по
         текущему state, а промис decode() отменить нечем — он доезжает сюда
         уже после show() следующей карточки, и снятый здесь loadTimer был бы
         таймером её кадра, а не нашего. Свой таймер устаревшего вызова к
         этому моменту уже снят cancelPending() из show(). */
      function finish(ok) {
        if (done) return;
        done = true;
        loader.onload = null;
        loader.onerror = null;
        if (gen !== captured || !state || !isMounted()) return;
        stopTimer('loadTimer');
        state.loader = null;
        /* Ревью правок волны 3, п.7: кадр смены повёл тик до ухода фокуса,
           а доехал после — не ставим и не докладываем: смена на паузе,
           очередь контроллера стоит на месте, и тик после возврата
           предложит тот же кадр (байты уже в кэше браузера). */
        if (slide && focusAway()) return;
        /* Кадр не пришёл — слои не трогаем: пустой герой хуже любого
           кадра. Кадр прошлого фильма, если он на экране, сменит заглушка
           (report(false) в startFrame → holdFrame, волна 3). */
        if (!ok) { report(false); return; }
        try {
          swapFrame(url, blur);
        } catch (e) {
          warn('hero: frame failed', e);
        }
        releaseLqip();
        report(true);
      }

      function shown() { finish(true); }

      loader.onload = function () { if (!decoding) shown(); };
      loader.onerror = function () { finish(false); };
      state.loader = loader;
      /* Страховочный таймаут. Решает по тому же признаку, что и неудачный
         decode(): байты есть — показываем (декодирует браузер при
         отрисовке), нет — оставляем предыдущий кадр. Через него же
         показывается кадр, когда decode() не резолвится вовсе: в скрытой
         вкладке Chromium картинки не растеризует, и промис висит без
         исхода (замер координатора на стенде 2026-09-21; WebView телевизора
         уходит в hidden на скринсейвере и при переключении приложения). */
      state.loadTimer = setTimeout(function () { finish(loaded()); }, LOAD_TIMEOUT);
      loader.src = url;
      /* Task 47: onload значит «байты пришли», а не «картинку можно
         показать»: декодирование в этот момент ещё впереди и на слабом ТВ
         происходит внутри растеризации, тайл за тайлом (at-raster decode,
         ресёрч §1.4 — это и видно как чёрные полосы на кадре). decode()
         резолвится, когда кадр уже декодирован и вставляется без
         синхронной работы.
         Реджект здесь НЕ бывает сменой src (частый случай в каруселях,
         ресёрч §4): у каждого вызова свой new Image, а src присваивается
         ровно один раз, выше. Значит остаются битые данные, упавший запрос
         и движок, отвергающий decode() без причины, — и решает единственный
         проверяемый признак, доехали ли байты. */
      if (decoding) {
        try {
          var decoded = loader.decode();
          if (decoded && typeof decoded.then === 'function') decoded.then(shown, function () { finish(loaded()); });
          else decoding = false;
        } catch (e) {
          /* decode() бросил синхронно — остаёмся на onload. */
          decoding = false;
        }
      }
    }

    /* Детали карточки: описание целиком, длительность/сезоны, жанры,
       логотипы, анонс серии. Один запрос на карточку, кэш сутки. */
    function loadDetails(card, captured) {
      try {
        if (!window.Lampa || !Lampa.Api || !Lampa.Api.sources || !Lampa.Api.sources.tmdb) return;
        var req = detailsRequest(mediaOf(card), card.id, langCode());
        /* Ревью фикс-раунда, Ф2 п.2: get ничего не возвращает (см.
           cancelPending), поэтому «детали в пути» — своя отметка, а не
           дескриптор запроса. Её читает park: оборванная загрузка на
           возврате доводится заново (state.stale). */
        state.detailsWait = true;
        Lampa.Api.sources.tmdb.get(
          req.url,
          req.params,
          function (json) {
            if (gen !== captured || !state) return;
            state.detailsWait = false;
            /* Ответ доехал в запаркованного героя: главная под другим
               экраном. Отрабатывать его здесь — значит поставить канвас
               атмосферы после уборки LC.fx.sweep() и тянуть кадр w1280,
               пока строится карточка; а если слайд главной Lampa уже снял
               из DOM (уход на два уровня, stop() у Activity), isMounted()
               ниже отбросил бы ответ молча, и скелетон описания горел бы
               на возврате. Поэтому — только пометка: resume покажет
               карточку заново, детали придут из кэша Lampa (life). */
            if (state.parked) { state.stale = true; return; }
            if (!isMounted()) return;
            state.details = json || null;
            var model = heroModel(card, state.details, words());
            /* Пустой ответ — тот же исход, что и ошибка: ждать больше нечего,
               скелетон гасим (иначе он горел бы до следующей карточки). */
            if (!state.details) model.pending = false;
            render(model, false);
            /* Task 21: атмосфера считается по ключевым словам из этого же
               ответа. В lite/off и при настройке «Выключены» вызов не
               создаёт ни канваса, ни кадрового цикла (src/52_fx.js). */
            applyFx();
            /* Волна 3: кадр героя выбирается по этому ответу (heroBackdrop
               в heroModel), если show() его ещё ждёт (startFrame). */
            startFrame(model, captured);
            /* «Несколько кадров»: кадры фильма — из этого же ответа. */
            startSlides(model, captured);
          },
          function () {
            if (gen !== captured || !state) return;
            state.detailsWait = false;
            if (state.parked) { state.stale = true; return; }
            if (!isMounted()) return;
            /* Деталей не будет — снимаем скелетон, оставляя то, что дала
               карточка ряда (заголовок, год, краткое описание). Флаг гасим в
               самой модели, а не классом на узле: отложенная подмена текста
               (swapTimer) перерисовала бы её и вернула скелетон. */
            var fallback = heroModel(card, null, words());
            fallback.pending = false;
            render(fallback, false);
            /* Волна 3: деталей не будет — кадр по данным ряда сразу, не
               дожидаясь FRAME_WAIT. */
            startFrame(fallback, captured);
          },
          { life: req.life }
        );
      } catch (e) {
        warn('hero: details failed', e);
      }
    }

    /* Волна 3 (проверка на ТВ 2026-09-24): кадр показа выбирается ОДИН раз.
       show() не грузит кадр по данным ряда сразу, как раньше: там
       backdrop_path — ключевой арт, повторяющий постер под героем
       («текст и обложка одинаковые»). Кадр выбирает heroBackdrop по images
       из ответа деталей; ответ из кэша Lampa (life — сутки) приходит
       синхронно, и ожидания нет вовсе, а за новым show() ждёт не дольше
       FRAME_WAIT — дальше кадр по данным ряда (таймер frameWait в show).
       state.framePath: null — ещё не выбран; '' — выбран постер вместо
       кадра (у фильма нет backdrop_path); путь — выбран кадр.
       Выбранный кадр поздний ответ не меняет: вторая смена кадра той же
       карточки — та самая подмена на глазах, от которой уходим. Одно
       исключение — постер: если детали принесли настоящий кадр, он
       ставится (прежнее правило «кадра не было в данных ряда, но он есть в
       деталях»). */
    function startFrame(model, captured) {
      if (!state || gen !== captured || !model) return;
      if (state.framePath) return;
      if (state.framePath === '' && !model.backdrop) return;
      stopTimer('frameWait');
      state.framePath = model.backdrop || '';
      loadFrame(model, captured, function (ok) {
        if (gen !== captured || !state) return;
        if (!ok) { holdFrame(captured); return; }
        state.frameId = state.shownId;
        stopTimer('holdTimer');
      });
    }

    /* Волна 3 (проверка на ТВ 2026-09-24, фото 2): текст нового фильма, а
       под ним кадр прошлого — новый кадр ещё едет (деталей ждём до
       FRAME_WAIT, сам w1280 на ТВ — сотни миллисекунд) или не загрузился
       вовсе. Кадр ЧУЖОГО фильма под новым текстом держится не дольше
       HOLD_MS от вывода текста (отсчёт заводит write в render — armHold)
       и уходит сразу, если новый кадр не загрузился, — пока фокус стоит на
       этой карточке. Ревью волны 3, п.1: фокус ушёл дальше — заглушки нет
       вовсе, при листании на экране остаётся кадр, который уже стоял
       (focusAway); вернулся — отсчёт с начала (onFocus).
       Заглушка — по образцу Lampa, у которой фон экрана — размытый постер
       фильма: постер новой карточки из ряда. Обычно он уже в кэше браузера
       — Lampa нарисовала его в ряду, — и тогда нет ни запроса, ни ожидания;
       у карточки, только что въехавшей в ряд, он может ещё грузиться (ревью
       волны 3, п.6). Нового слоя нет ни в каком случае: он встаёт в тот же
       слой кадра и растягивается cover'ом,
       мягкость даёт сам апскейл (в ряду постер w200–w500 — по настройке
       качества постеров Lampa), без filter:blur, который на полноэкранном
       слое в lite запрещён. Слой получает ту же
       метку размытия, что постер фильма без кадра (loadFrame). Кадр
       прошлого фильма, размытый CSS, дешевле не был бы (filter на весь
       экран) и остался бы кадром чужого фильма; подложке LQIP нового
       фильма нужен выбранный кадр — детали и ещё один запрос.
       Постера в ряду ещё нет (Lampa ставит его, когда карточка появляется
       на экране, до того там ./img/img_load.svg) — нейтральный фон
       страницы: гаснут оба слоя кадра и подложка.
       state.frameId — чей кадр на экране: возврат на тот же фильм (resume
       с оборванной загрузкой) свой кадр не прячет, а первый показ героя
       заглушки не ждёт вовсе — под ним ничего нет. */
    function holdFrame(captured, late) {
      if (!state || gen !== captured) return;
      stopTimer('holdTimer');
      if (String(state.frameId) === String(state.shownId)) return;
      if (!state.frameUrl && !state.lqipUrl) return;
      /* Ревью волны 3, п.1: фокус уже на другой карточке — заглушку не
         ставим (фон при листании не мигает), она ждёт возврата фокуса. Этим
         путём приходит ошибка кадра (startFrame); отсчёт уход фокуса
         снимает сам (onFocus). */
      if (focusAway()) {
        state.holdDue = true;
        return;
      }
      /* Ревью волны 3, п.2: байты нового кадра уже доехали (тот же признак
         complete && naturalWidth, что у страховочного таймаута loadFrame),
         и его декодирует браузер — кадр вот-вот встанет. Заглушка на этом
         стыке — короткая вспышка постера (живьём 26 мс при возврате из
         карточки), поэтому ещё HOLD_DECODE, один раз: декодирование,
         которое не кончается (скрытая вкладка), заглушку не держит. */
      var loader = state.loader;
      if (!late && loader && loader.complete && loader.naturalWidth) {
        state.holdTimer = setTimeout(function () {
          if (gen !== captured || !state) return;
          state.holdTimer = null;
          holdFrame(captured, true);
        }, HOLD_DECODE);
        return;
      }
      var poster = state.holdPoster;
      try {
        if (poster) {
          swapFrame(poster, true);
        } else {
          state.stage.find('.lumen-hero__bg').removeClass('is-active');
          state.frameUrl = '';
          if (state.lqipUrl) {
            stopTimer('lqipTimer');
            var lqip = state.stage.find('.lumen-hero__lqip');
            lqip.removeClass('is-active');
            lqip.removeAttr('src');
            state.lqipUrl = '';
          }
        }
        /* На экране больше нет прошлого фильма — второй раз не прячем. */
        state.frameId = state.shownId;
      } catch (e) {
        warn('hero: hold failed', e);
      }
    }

    /* Ревью волны 3, п.1: фокус стоит на другой карточке, чем показанная, —
       листание идёт дальше (её show() ещё впереди, через DELAY). pending
       пуст у героя, показанного без события фокуса (mount, resume без
       карточки в фокусе), — тогда фокус никуда не ушёл. */
    function focusAway() {
      return !!(state && state.pending && String(state.pending.id) !== String(state.shownId));
    }

    /* Отсчёт HOLD_MS до заглушки: кадр на экране чужой, а текст показа уже
       выведен (write в render) или фокус вернулся на показанную карточку
       (onFocus). Заведённый не перезаводится. */
    function armHold() {
      if (!state || state.holdTimer) return;
      if (String(state.frameId) === String(state.shownId)) return;
      var held = gen;
      state.holdTimer = setTimeout(function () {
        if (gen !== held || !state) return;
        state.holdTimer = null;
        holdFrame(held);
      }, HOLD_MS);
    }

    /* Адрес постера карточки из ряда, если он уже настоящий: до появления
       карточки на экране Lampa держит там svg-заглушку загрузки. */
    function rowPoster(el) {
      var src = el ? posterOf(el) : '';
      return src && !/\.svg(\?|#|$)/i.test(src) ? src : '';
    }

    /* Показать героя для карточки. Вызывается только из отложенного тика
       обработчика фокуса (или из mount для уже сфокусированной карточки).
       el — узел карточки в ряду, если он есть: его постер — заглушка
       holdFrame. poster — заглушка, когда узла нет: resume без карточки в
       фокусе показывает тот же фильм заново (ревью правок волны 3, п.6). */
    function show(card, el, poster) {
      if (!state || !card) return;
      try {
        var captured = ++gen;
        cancelPending();
        /* Слайдшоу прошлой карточки — вместе с её таймером. */
        cancelSlides();
        state.shownId = card.id;
        /* Сама карточка показанного фильма — для resume без карточки в
           фокусе (ревью 84c7b27..de0e2c8, п.4). */
        state.shownCard = card;
        state.details = null;
        state.model = null;
        /* Правка 2026-09-22: новая карточка — новое ожидание логотипа
           (writeTitle). Решение «ждать больше нечего», принятое для
           предыдущей, на неё не распространяется. */
        state.titleForced = false;
        /* Task 21: атмосфера прошлой карточки уходит сразу — иначе снег с
           рождественского фильма висел бы над кадром следующего, пока не
           придут его детали. */
        clearFx();
        /* Волна 3: кадр выбирается по деталям (startFrame) — сначала
           запрос, потом, если ответ не пришёл синхронно из кэша, отсчёт
           FRAME_WAIT до кадра по данным ряда. */
        state.framePath = null;
        /* Волна 3: на экране кадр — отсчёт заглушки заведёт вывод текста
           этого показа (write в render), если кадр к тому мигу чужой. */
        state.holdPoster = el ? rowPoster(el) : (poster || '');
        state.holdDue = !!(state.frameUrl || state.lqipUrl) && motionMode() !== 'off';
        var model = heroModel(card, null, words());
        render(model, true);
        loadDetails(card, captured);
        /* В «Выкл» кадр не грузится вовсе (loadFrame) — и ждать нечего. */
        if (gen === captured && state && state.framePath === null && motionMode() !== 'off') {
          state.frameWait = setTimeout(function () {
            if (gen !== captured || !state) return;
            state.frameWait = null;
            startFrame(heroModel(card, null, words()), captured);
          }, FRAME_WAIT);
        }
      } catch (e) {
        warn('hero: show failed', e);
      }
    }

    /* ------------------------------------------------------------------ */
    /* Слушатель фокуса.                                                   */
    /* ------------------------------------------------------------------ */

    /* Позиция ряда карточки среди рядов главной. Считается по самой
       карточке, а не подпиской Lampa.Listener('line'): вторая подписка жила
       бы параллельно слушателю фокуса и давала бы второй источник правды о том,
       какой ряд сейчас в фокусе. -1 — ряд не найден (мини-герой сетки). */
    function rowIndex(el) {
      try {
        var line = $(el).closest('.items-line');
        if (!line || !line.length) return -1;
        return line.index();
      } catch (e) {
        return -1;
      }
    }

    /* Сжатое состояние: текст героя уезжает вверх (design-spec-main §0.2,
       раскадровка 23б), а освободившуюся высоту забирают ряды — они
       поднимаются к половине экрана. Волна 3 (ТВ 2026-09-24): сам кадр в
       сжатом состоянии больше не едет — он в неподвижном слое на весь экран
       (buildStage), и ряды наезжают на него снизу, а под ними его закрывает
       пол слоя (.lumen-hero__floor, по классу .lumen-rows-up ниже).

       Правка пользователя 2026-09-17 (второй круг): класс на корне
       активности (.lumen-rows-up) — это и есть та передача места. Раньше
       сжимался только кадр, и под ним оставалась пустая полоса в половину
       экрана. Второго признака «фокус ниже первого ряда» не заводим: и кадр,
       и ряды переключает одна эта функция, а слушателей прокрутки у нас
       по-прежнему нет.

       Task 36: кроме двух классов функция не делает ничего. Всю геометрию
       обоих состояний задаёт таблица стилей, и переключение класса не
       читает и не пишет ни одного размера — потому переход и состоит теперь
       из одних transform (текст, логотип, область рядов) и одного opacity
       (пол слоя кадра), без единого свойства раскладки. */
    function setCompact(on) {
      if (!state) return;
      /* Ревью Task 64: то же состояние нужно и слою атмосферы — читать класс
         с узла на каждом кадре цикла частиц дороже, чем держать флаг. */
      state.compact = !!on;
      /* «Несколько кадров»: фокус ушёл в ряды — кадры не меняются, как не
         рисуются и частицы; вернулся на первый ряд — смена продолжается. */
      if (state.slides) {
        /* Играющий ролик держит свою паузу (trailerOn) — развернувшись, кадры
           ждут его конца; фокус на другой карточке — тоже (slidesHeld). */
        try { if (on) state.slides.pause(); else if (!slidesHeld()) state.slides.resume(); } catch (eSl) { }
      }
      state.node.toggleClass('lumen-hero--compact', on);
      try { state.root.toggleClass('lumen-rows-up', on); } catch (e) {}
    }

    /* Фокус ниже первого ряда — герой сжат. Мини-герой сетки сжат всегда. */
    function updateCompact(el) {
      if (!state || state.fixedCompact) return;
      var index = rowIndex(el);
      if (index < 0) return;
      setCompact(index > 0);
    }

    /* Адрес постера карточки из её <img>: обычно уже отрисован и лежит в
       кэше браузера, у только что въехавшей в ряд карточки может ещё
       грузиться. */
    function posterOf(el) {
      try {
        return $(el).find('.card__img').attr('src') || '';
      } catch (e) {
        return '';
      }
    }

    /* Правка пользователя 2026-09-17 (третий круг): акцент и подкраска фона
       берутся с карточки, на которой ОСТАНОВИЛИСЬ, — отдельным таймером на
       ACCENT_DELAY. Сторож тот же, что у смены героя: state.pending меняется
       на каждом фокусе, поэтому отложенный тик, доехавший после перевода
       фокуса, выходит первой же строкой и ни одного расчёта не запускает.
       Своего поколения (gen) здесь нет намеренно: gen поднимается на каждом
       show(), то есть уже через 350 мс покоя, — трёхсекундный тик по нему
       не пережил бы даже собственную карточку. */
    function scheduleAccent(card) {
      stopTimer('accentTimer');
      /* Task 60 (ревью): фокус ушёл на другую карточку — идущий переход
         цвета обрывается. Считать его дешёвым во время прокрутки нельзя:
         шестнадцать перезаписей узла подкраски по 100 мс попали бы ровно в
         тот момент, когда ряд едет, а это самый дорогой момент главной
         (21 fps на Philips 50PUS8057, раздел «Что известно точно» в
         docs/plans/2026-09-21-lumen-phase5-tv-fix.md). Цвет замирает там,
         где его застали, а не прыгает к цели: скачок половины пути во
         время прокрутки — ровно та «резкая смена тонов», от которой уходим.
         Вернулись на ту же карточку — путь доигрывается с этого места
         (apply в src/57_color.js). */
      try {
        if (LC.accent && typeof LC.accent.stopTween === 'function') LC.accent.stopTween();
      } catch (eStop) {
        warn('hero: accent stop failed', eStop);
      }
      state.accentTimer = setTimeout(function () {
        if (!state) return;
        state.accentTimer = null;
        if (state.pending !== card) return;
        if (!isMounted()) return;
        try {
          if (LC.accent && typeof LC.accent.applyFor === 'function') LC.accent.applyFor(card);
        } catch (e) {
          warn('hero: accent failed', e);
        }
      }, ACCENT_DELAY);
    }

    function onFocus(el) {
      if (!state) return;
      var card = el.card_data;
      if (!card || card.id == null) return;

      /* Task 37: фокус не сменился — уходим. Ни один таймер (350 мс кадр,
         3 с акцент, 8 с ролик) не перезапускается: событие на той же
         карточке шлёт сама Lampa, когда возвращает фокус на место. Цепочка:
         Controller.collectionFocus зовёт SpatialNavigator.focus на прежнем
         элементе (app.min.js:46481), тот шлёт своё событие 'focus'
         (vender/navigator/navigator.js:657-684), мост Navigator.follow
         ('focus') переводит его в Controller.focus (app.min.js:56069-56071),
         и уже он шлёт 'hover:focus' (:46438). Ролик, начавший играть, от
         такого возврата обрываться не должен. */
      if (state.focusEl === el) return;
      state.focusEl = el;

      updateCompact(el);

      state.focusAt = Date.now();
      state.pending = card;
      stopTimer('timer');
      /* Акцент ждёт свои 3 с независимо от того, меняется герой или нет:
         вернулись на ту же карточку — цвет у неё уже стоит, и applyFor на
         том же постере возьмёт его из кэша, не пересобирая стилей. */
      scheduleAccent(card);
      /* Task 28: любой перевод фокуса снимает играющий ролик и заводит отсчёт
         заново. Сравнение с trailerCard оставлено и после Task 37: гард выше
         ловит повторное событие на ТОМ ЖЕ УЗЛЕ, а этот — ту же карточку на
         другом узле (ряд перестроился, карточка приехала заново). Иначе
         идущий ролик гас бы на ровном месте. */
      if (state.trailerCard !== card) {
        cancelTrailer();
        state.trailerCard = card;
        scheduleTrailer(card);
      }
      /* Тот же фильм под фокусом (возврат на ту же карточку, перерисовка
         ряда) — ни кадра, ни запроса. Ревью волны 3, п.1: отсчёт заглушки,
         снятый уходом фокуса (ниже), заводится заново — от возврата, как
         от вывода текста. Текст ещё не выведен (swapTimer) — отсчёт заведёт
         сам вывод. */
      if (state.shownId === card.id) {
        if (state.holdDue && !state.swapTimer) {
          state.holdDue = false;
          armHold();
        }
        /* Ревью правок волны 3, п.7: смена кадров, поставленная на паузу
           уходом фокуса (ниже), продолжается — если не держит другая
           причина (slidesHeld). */
        if (state.slides && !slidesHeld()) {
          try { state.slides.resume(); } catch (eRs) { warn('hero: slides resume failed', eRs); }
        }
        return;
      }

      /* Ревью волны 3, п.1: фокус ушёл с показанной карточки — её
         заглушка не встаёт, пока идёт листание: живьём на шаге 550 мс
         отсчёт срабатывал через 230 мс после ухода фокуса и растягивал на
         весь экран постер карточки, с которой фокус уже ушёл. Отсчёт ждёт
         возврата фокуса (выше); show() новой карточки его перепишет. */
      if (state.holdTimer) {
        stopTimer('holdTimer');
        state.holdDue = true;
      }
      /* Ревью правок волны 3, п.7: и смена кадров показанного фильма — на
         паузу до возврата фокуса; show() новой карточки её снимет. */
      if (state.slides) {
        try { state.slides.pause(); } catch (ePs) { warn('hero: slides pause failed', ePs); }
      }

      var captured = gen;
      state.timer = setTimeout(function () {
        if (gen !== captured || !state) return;
        state.timer = null;
        if (!isMounted()) return;
        if (state.pending !== card) return;
        if (!shouldUpdate(state.shownId, card.id, Date.now() - state.focusAt, DELAY)) return;
        show(card, el);
      }, DELAY);
    }

    /* Цель события — сама карточка, поэтому проверяем её собственные классы,
       а не ищем карточку среди предков: оба события фокуса Lampa шлёт ровно
       на тот элемент, который получает фокус (Utils.trigger(target, …) —
       пульт на app.min.js:46438, мышь на :46363). В корне активности фокус
       получают и не-карточки (кнопки шапки, пункты меню) — они отсеиваются
       здесь. */
    function onFocusEvent(e) {
      /* Запаркованный герой (главная под открытой карточкой) на фокус не
         отвечает: события на скрытой главной не ждём, но если оно придёт,
         заводить таймеры и запросы под чужим экраном незачем. */
      if (!state || state.parked) return;
      try {
        var el = e && e.target;
        if (!el || !el.classList || !el.classList.contains('card')) return;
        onFocus(el);
      } catch (err) {
        warn('hero: focus listener failed', err);
      }
    }

    /* Task 37: фокус ловится нативным слушателем в фазе ЗАХВАТА на корне
       активности.

       Task 68: подписку ставит общий LC.focus.capture (src/11_focus.js) —
       он вешает ОБА события фокуса, 'hover:focus' (пульт) и 'hover:hover'
       (мышь, app.min.js:46360-46364). До этого герой слушал только первое и
       на мышь не отзывался вовсе: класс focus переезжал на карточку под
       курсором, а кадр и мета оставались от той, где стоял фокус пульта.

       Почему захват. Событие фокуса создаётся Lampa как
       initEvent(name, false, true) (Utils.trigger, app.min.js:4497-4500),
       второй аргумент — bubbles, то есть событие НЕ всплывает:
       ни делегированное $(root).on(…, '.card', …), ни слушатель на фазе
       всплытия его не увидят — замер на живой Lampa 2026-09-18 дал ноль
       срабатываний у делегированного jQuery-обработчика и срабатывание у
       нативного в захвате. Вниз по дереву, к цели, событие проходит всегда.
       Тот же приём и по той же причине — у меню карточки ('hover:long',
       src/63_cardmenu.js). Мышиное 'hover:hover' идёт тем же Utils.trigger
       (app.min.js:46363), то есть про всплытие верно и для него.

       Почему не MutationObserver, как было раньше. Наблюдатель стоял на
       attributeFilter ['class'] + subtree, то есть на КАЖДУЮ мутацию класса
       во всей активности. Одно нажатие стрелки на ТВ даёт их десятки:
       Controller.focus (app.min.js:46437-46446) снимает класс focus со ВСЕЙ
       коллекции навигации, обходя её в цикле, и ставит его на цель
       (removeClass(['focus']) + toggleClass, :46441-46442, сам обход —
       :46422-46429; мутаций столько же, сколько элементов в коллекции, то
       есть десятки). Сверх того колбэк срабатывал на любой наш собственный
       класс, поставленный внутри того же корня (узел героя лежит в нём),
       снова находил карточку с классом focus и повторял весь onFocus — а
       значит и перезапускал таймеры акцента и трейлера. Слушатель события
       даёт ровно один вызов на один перевод фокуса.

       Побочное улучшение: те мутации класса стоят под if
       (Platform.screen('tv')) (app.min.js:46440), то есть НЕ на ТВ их не было
       вовсе — прежний наблюдатель фокус там не ловил в принципе, и герой на
       десктопе жил только тем, что показывал showFocused. Слушатель события
       работает на всех платформах одинаково. */
    function listenFocus(root) {
      try {
        var node = root && root[0];
        if (!node) return;
        state.focusHandler = onFocusEvent;
        if (!LC.focus.capture(node, state.focusHandler)) state.focusHandler = null;
      } catch (e) {
        warn('hero: listen failed', e);
      }
    }

    /* Снятие слушателя. Ссылка на обработчик и корень берутся из снимаемого
       состояния: unmount обнуляет state ДО уборки, а removeEventListener
       обязан получить ту же функцию и ту же фазу, что и подписка. */
    function unlistenFocus(s) {
      if (!s || !s.focusHandler) return;
      try {
        LC.focus.release(s.root && s.root[0], s.focusHandler);
      } catch (e) {
        warn('hero: unlisten failed', e);
      }
      s.focusHandler = null;
    }

    /* Карточка, которая уже в фокусе на момент монтирования (возврат из
       карточки на главную — Lampa восстанавливает фокус сама, и события
       'hover:focus' при этом не будет: класс focus на карточке уже стоит). */
    function showFocused(root) {
      try {
        var el = root.find('.card.focus');
        if (el && el.length && el[0] && el[0].card_data) {
          updateCompact(el[0]);
          /* Task 37 (ревью): фокус Lampa восстанавливает синхронно внутри
             activity.start() — Controller.toggle('content') зовёт toggle
             контроллера с collectionFocus (app.min.js:45441), и это
             происходит ДО Listener.send('activity','start')
             (app.min.js:46027), в обработчике которого мы только монтируем
             героя и вешаем слушатель. Событие 'hover:focus' к тому моменту
             уже прошло мимо — героя показываем здесь. state.focusEl тут
             намеренно НЕ ставится: первое настоящее событие фокуса должно
             пройти полный путь и завести таймеры. */
          show(el[0].card_data, el[0]);
        }
      } catch (e) {}
    }

